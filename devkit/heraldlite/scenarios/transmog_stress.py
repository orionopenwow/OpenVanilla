#!/usr/bin/env python3
"""transmog_stress.py - writes one Herald Lite scenario per bot that hammers the transmog realm side.

    python3 transmog_stress.py <out dir> [bots=8] [steps=150] [seed=1]

Each bot (a level 60 GM Hunter, HL_USER = HERALD<letter>) collects a few looks, then runs a seeded
random mix of every ".wnl tm" command: valid saves, refused ones (wrong class, wrong slot, not
collected, away from the Transmogrifier), hidden slots, outfit switches, situations, names with odd
characters, icons, custom sets, unlocks, illusions, malformed and oversized lines, and relogs in the
middle of it all. It ends on a fixed check: the realm still answers, a save works, the look shows on
the visible slot. Run them side by side (run_transmog_stress.sh) and check the server stayed up and
the tables stayed consistent (that script does both).
"""
import os
import random
import sys

NPC = ".go xyz -4835.5 -855.2 502 0"
AWAY = ".go xyz -5590 -520 400 0"
FEET = [16941, 16849, 16462]          # collected by every bot (worn or added below)
LEGS = [16938, 16467]
NOT_HUNTER = [16912, 16949]           # cloth, a shaman's mail
NEVER = [16675, 9999999, 0]
SLOTS = [0, 2, 3, 4, 5, 6, 7, 8, 9, 14, 15, 16, 17, 18, 1, 10, 11, 12, 13, 19, 99]


def junk(r):
    choices = [
        "tm", "tm ", "tm x", "tm save", "tm save 1", "tm save 1 ", "tm save x 7:1:0", "tm save 1 7",
        "tm save 1 7:", "tm save 1 :::", "tm save 1 7:1:0,7:1:0", "tm save -1 7:16941:0",
        "tm save 4294967295 7:16941:0", "tm save 1 4294967295:1:0", "tm save 1 7:-5:0",
        "tm save 1 7:16941:4294967295", "tm use -3", "tm use 999", "tm situ 1 -1", "tm situ 1 99999999999",
        "tm name 1 " + "A" * 300, "tm name 1 '; DROP TABLE transmog_outfit; --", "tm name 1 été ☃",
        "tm icon 1 -7", "tm cset save 0 ~", "tm cset save 0 x~7:16941:0/" * 3, "tm cset del 0",
        "tm cset del 999999", "tm cset save 7 Ghost~7:16941:0", "tm col 999", "tm look -1", "tm outfit 88",
        "tm " + "z" * 250, "tm save 1 " + ",".join("7:16941:0" for _ in range(40)),
    ]
    return r.choice(choices)


def step(r, outfits):
    o = r.randint(0, outfits)
    k = r.random()
    if k < 0.20:
        slot = r.choice([7, 7, 6, 0, 2, 14, 18, 3])
        look = r.choice(FEET if slot == 7 else LEGS if slot == 6 else [-1, 0])
        if r.random() < 0.15:
            look = r.choice(NOT_HUNTER + NEVER)
        return f"send .wnl tm save {max(1, o)} {slot}:{look}:0"
    if k < 0.28:
        return f"send .wnl tm cost {max(1, o)} 7:{r.choice(FEET)}:0,0:-1:0"
    if k < 0.40:
        return f"send .wnl tm use {o}"
    if k < 0.46:
        return f"send .wnl tm situ {max(1, o)} {r.choice([0, 2, 1, 16, 256, 4096 | 2, 1048576, 65536])}"
    if k < 0.50:
        return f"send .wnl tm name {max(1, o)} {r.choice(['Raid night', 'PvP', 'x', 'Long ' * 8, 'Dwarf-ish'])}"
    if k < 0.53:
        return f"send .wnl tm icon {max(1, o)} {r.choice(FEET + LEGS)}"
    if k < 0.62:
        return f"send .wnl tm {r.choice(['hi', 'outfits', 'known', 'ill', 'sets', 'cset list'])}"
    if k < 0.70:
        return f"send .wnl tm col {r.choice(SLOTS)}"
    if k < 0.74:
        return f"send .wnl tm look {r.choice(FEET + LEGS + NOT_HUNTER + NEVER)}"
    if k < 0.78:
        return f"send .wnl tm outfit {o}"
    if k < 0.82:
        return f"send .wnl tm cset save 0 Set{r.randint(1, 999)}~7:{r.choice(FEET)}:0/0:-1:0"
    if k < 0.84:
        return f"send .wnl tm cset del {r.randint(1, 40)}"
    if k < 0.85:
        return "send .wnl tm unlock"
    if k < 0.95:
        return "send .wnl " + junk(r)
    if k < 0.975:
        return "send " + r.choice([NPC, AWAY])
    return "RELOG"


def scenario(bot, steps, seed):
    r = random.Random(seed * 1000 + bot)
    lines = [f"# transmog stress bot {bot} (seed {seed}): generated by transmog_stress.py", "login",
             "expect wnl HI within 15s", "send .wnl hi", "send " + NPC, "wait 2s",
             "send .additem 16941", "send .additem 16849", "send .additem 16938",
             "send .wnl tm hi", "expect wnl TM matches ^on, within 15s"]
    for i in range(steps):
        s = step(r, 4)
        if s == "RELOG":
            lines += ["logout", "wait 1s", "login", "expect wnl HI within 15s", "send .wnl hi", "send " + NPC,
                      "send .wnl tm hi", "expect wnl TM matches ^on, within 15s"]
        else:
            lines.append(s)
        if i % 10 == 9:
            lines.append("wait 300ms")
    lines += [
        "# the realm still answers, a save works, the look is what others see",
        "send " + NPC, "wait 2s",
        "send .wnl tm situ 1 0", "send .wnl tm situ 2 0", "send .wnl tm situ 3 0", "send .wnl tm situ 4 0",
        "wait 3s",
        "send .wnl tm save 1 7:16941:0,0:0:0",
        "expect wnl TM matches ^(saved,1,\\d+|err,money)$ within 15s",
        "send .wnl tm use 1",
        "expect wnl TM matches ^active,1 within 15s",
        "expect visible 7 16941 within 10s",
        "send .wnl tm use 0",
        "expect wnl TM matches ^active,0 within 15s",
        "send .wnl tm hi",
        "expect wnl TM matches ^on,\\d+,50,0, within 15s",
        "logout",
    ]
    return "\n".join(lines) + "\n"


def main():
    out = sys.argv[1]
    bots = int(sys.argv[2]) if len(sys.argv) > 2 else 8
    steps = int(sys.argv[3]) if len(sys.argv) > 3 else 150
    seed = int(sys.argv[4]) if len(sys.argv) > 4 else 1
    os.makedirs(out, exist_ok=True)
    for b in range(bots):
        with open(os.path.join(out, f"stress_{b}.txt"), "w") as f:
            f.write(scenario(b, steps, seed))
    print(f"{bots} scenarios of {steps} steps in {out}")


if __name__ == "__main__":
    main()
