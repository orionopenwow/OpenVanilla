-- Assistant: the in-game prompt library for the AI agent the player runs outside the game.
local T, api = ...

local function assistant() return T.addon("Assistant") end

T.test("Assistant: registers with a plain name, a schema and its slash commands", function()
    local env = assistant()
    local W = env.WenillaCore
    T.eq(W.schemas.Assistant.title, "Assistant")
    T.eq(env.GetAddOnMetadata("Assistant", "Title"), "Assistant")
    T.eq(W:Setting("Assistant", "escButton"), false, "Esc menu button off by default")
    local joined = false
    for _, id in ipairs(W.ADDONS) do if id == "Assistant" then joined = true end end
    T.ok(joined, "joins the Addons window")
    T.ok(env.SlashCmdList.ASSISTANT, "/assistant")
    T.ok(table.getn(env.Assistant.PROMPTS) >= 6, "ships the prompt library")
    for _, p in ipairs(env.Assistant.PROMPTS) do
        T.ok(p.id and p.title and p.text and p.text ~= "", "every prompt has an id, title and text")
    end
end)

T.test("Assistant: /assistant opens the list; picking a prompt puts it in the copy box, selected", function()
    local env = assistant()
    local A = env.Assistant
    env.__slash("/assistant")
    local win = env.AssistantFrame
    T.shown(win)
    T.ok(api.screen_has(env, "Tour my Open Vanilla folder", win), "the first prompt is listed")
    T.ok(api.screen_has(env, "Make my first addon", win))
    T.eq(env.AssistantCopyBox:GetText(), A.PROMPTS[1].text, "the first prompt is chosen")
    T.eq(env.__focus, env.AssistantCopyBox, "the copy box has focus, so Ctrl+C copies")
    T.ok(A.highlighted, "and its text is selected")
    api.click_text(env, "Make my first addon", win)
    local p = A.Find("first-addon")
    T.eq(env.AssistantCopyBox:GetText(), p.text)
    T.has(env.AssistantCopyBox:GetText(), "Lua 5.0")
    T.ok(api.screen_has(env, "Works on:", win), "says what it works on")
    T.ok(api.screen_has(env, "The AI runs outside the game", win), "points out the AI runs outside the game")
    T.ok(api.screen_has(env, "Ctrl+C", win))
end)

T.test("Assistant: the copy box is read-only and Select all selects again", function()
    local env = assistant()
    local A = env.Assistant
    env.__slash("/assistant")
    local box = env.AssistantCopyBox
    local text = box:GetText()
    api.type(box, "oops")
    T.eq(box:GetText(), text, "typing puts the prompt back")
    box:ClearFocus()
    A.highlighted = nil
    api.click_text(env, "Select all", env.AssistantFrame)
    T.eq(env.__focus, box)
    T.ok(A.highlighted)
end)

T.test("Assistant: remembers the last prompt across a relog", function()
    local env = assistant()
    env.__slash("/assistant")
    api.click_text(env, "Change my realm's XP rate", env.AssistantFrame)
    env = T.relog(env)
    env.__slash("/assistant")
    T.eq(env.AssistantCopyBox:GetText(), env.Assistant.Find("xp-rate").text)
end)

T.test("Assistant: How it works tab, Escape closes, /assistant toggles", function()
    local env = assistant()
    env.__slash("/assistant how")
    local win = env.AssistantFrame
    T.shown(win)
    T.ok(api.screen_has(env, "Set up the workspace", win))
    T.ok(api.screen_has(env, "official realm", win), "says what it can't touch")
    T.ok(api.screen_has(env, "Never paste passwords", win))
    T.ok(api.press_escape(env), "Escape closes it")
    T.hidden(win)
    env.__slash("/ai")
    T.shown(win, "/ai alias")
    env.__slash("/ai")
    T.hidden(win)
end)

T.test("Assistant: Esc menu button under AddOns, and the Open Vanilla tools entry", function()
    local env = T.suite()
    env.ClassicPlus_Manager:SetSetting("Assistant", "escButton", true)
    api.tick(env, 0.1)
    env.GameMenuFrame:Show()
    T.eq(env.GameMenuButtonAssistant:GetText(), "Assistant")
    T.eq(env.GameMenuButtonAddOns:GetText(), "AddOns", "AddOns keeps its button")
    api.click(env.GameMenuButtonAssistant)
    T.hidden(env.GameMenuFrame, "the Esc menu closes")
    T.shown(env.AssistantFrame, "and the Assistant opens")
    env.AssistantFrame:Hide()
    env.GameMenuFrame:Show()
    api.click(env.GameMenuButtonOVTools)
    api.click_text(env, "Assistant", env.OVToolsFrame)
    T.shown(env.AssistantFrame, "the Game Menu's Open Vanilla list opens it too")
end)

T.test("Assistant: the Esc button follows its switch and Pure Vanilla", function()
    local env = assistant()
    T.no(env.GameMenuButtonAssistant and env.GameMenuButtonAssistant:IsShown(), "off by default: no button")
    env.ClassicPlus_Manager:SetSetting("Assistant", "escButton", true)
    api.tick(env, 0.1)
    local h = env.GameMenuFrame:GetHeight()
    env.ClassicPlus_Manager:SetSetting("Assistant", "escButton", false)
    api.tick(env, 0.1)
    T.no(env.GameMenuButtonAssistant:IsShown(), "switched off: no button")
    T.eq(env.GameMenuFrame:GetHeight(), h - 24, "and the menu shrinks back")
    env.ClassicPlus_Manager:SetSetting("Assistant", "escButton", true)
    api.tick(env, 0.1)
    T.ok(env.GameMenuButtonAssistant:IsShown())
    T.eq(env.GameMenuFrame:GetHeight(), h)
    env.__slash("/assistant")
    env.__slash("/vanilla")
    T.hidden(env.AssistantFrame, "Pure Vanilla hides the window")
    T.no(env.GameMenuButtonAssistant:IsShown(), "and the button")
    env.__slash("/assistant")
    T.hidden(env.AssistantFrame, "and it stays closed")
    T.has(api.chat_text(env), "Assistant is switched off")
end)
