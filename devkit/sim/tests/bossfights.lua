-- The site's Fight now: ?mode=boss&raid=<raid> -> the play page -> WenillaCore:Dispatch("BFH", raid)

T.test("Boss Fights: no window on arrival without the site's hint (duelers share the hangout)", function()
    local env = bf()
    connect(env, HI)
    api.tick(env, 2)
    T.ok(not env.BossFightsFrame or not env.BossFightsFrame:IsVisible(), "no window without a hint")
    T.ok(not string.find(sent(env), "bf mode boss", 1, true), "no mode change without a hint")
    T.ok(not string.find(sent(env), "bf go", 1, true), "no trip to Gurubashi without a hint")
end)

T.test("Boss Fights: the site's hint opens the Queue tab on that raid; in Boss Fights already, no trip", function()
    local env = bf()
    connect(env, HI)                                     -- hi says: in Boss Fights
    env.WenillaCore:Dispatch("BFH", "mc")
    api.tick(env, 2)
    T.shown(env.BossFightsFrame)
    T.eq(env.BossFights.pick.raid, "mc")
    T.has(texts(env), "Queue up")
    T.has(sent(env), "wf bf mode boss")
    T.ok(not string.find(sent(env), "bf go", 1, true), "already in Boss Fights: no go")
end)

T.test("Boss Fights: a hint before the realm's hello waits for it, then takes a dueler to Gurubashi, once", function()
    local env = bf()
    connect(env)
    env.OpenVanillaModeHint("boss", "onyxia")
    api.tick(env, 1)
    T.ok(not env.BossFightsFrame or not env.BossFightsFrame:IsVisible(), "nothing before the hello")
    T.ok(not string.find(sent(env), "bf mode boss", 1, true), "nothing sent before the hello")
    api.server_packet(env, "BF", "hi,1,0,,,0,onyxia:0:1:10;mc:0:1:10")    -- not in Boss Fights
    api.tick(env, 2)
    T.shown(env.BossFightsFrame)
    T.eq(env.BossFights.pick.raid, "onyxia")
    T.has(sent(env), "wf bf mode boss")
    T.has(sent(env), "wf bf go onyxia")
    local n = count(env, "bf mode boss")
    api.server_packet(env, "BF", "hi,1,1,onyxia,,0,onyxia:0:1:10;mc:0:1:10")
    api.tick(env, 2)
    T.eq(count(env, "bf mode boss"), n, "the hint applies once")
end)

