T.test("Boss Fights: the pop, the run's timer, bosses, a wipe and the clear", function()
    local env = bf()
    open(env, HI)
    api.server_packet(env, "BF", "pop,5,onyxia,2,fortified")
    T.shown(env.BossFightsReady)
    local r = texts(env, env.BossFightsReady)
    T.has(r, "Onyxia's Lair, Tier 2")
    T.has(r, "Fortified")
    T.hidden(env.BossFightsFrame)
    api.server_packet(env, "BF", "in,5,onyxia,2,10")
    api.server_packet(env, "BF", "run,5,onyxia,2,0:00,0/1")
    T.shown(env.BossFightsHud)
    local h = texts(env, env.BossFightsHud)
    T.has(h, "Onyxia")
    T.has(h, "Tier 2")
    T.has(h, "Fortified")
    T.has(h, "Bosses 0/1")
    api.server_packet(env, "BF", "pull")
    api.tick(env, 65)
    T.has(texts(env, env.BossFightsHud), "1:0")
    api.server_packet(env, "BF", "wipe,1")
    T.has(texts(env, env.BossFightsHud), "Wipes 1")
    api.server_packet(env, "BF", "boss,0,Onyxia,6:42")
    h = texts(env, env.BossFightsHud)
    T.has(h, "Bosses 1/1")
    T.has(h, "6:42")
    api.server_packet(env, "BF", "end,1,6:42,2,1,3")
    T.hidden(env.BossFightsHud)
    T.shown(env.BossFightsEnd)
    local e = texts(env, env.BossFightsEnd)
    T.has(e, "Cleared!")
    T.has(e, "6:42")
    T.has(e, "Deaths 2")
    T.has(e, "Wipes 1")
    T.has(e, "Tier 3 unlocked")
    api.click_text(env, "Back to Gurubashi", env.BossFightsEnd)
    api.pump(env)
    T.has(sent(env), "wf bf go")
end)

T.test("Boss Fights: a run that ends without a clear, and /bf commands", function()
    local env = bf()
    open(env, HI)
    api.server_packet(env, "BF", "pop,6,mc,1,none")
    api.server_packet(env, "BF", "end,0,12:00,4,3,1")
    T.has(texts(env, env.BossFightsEnd), "The run is over")
    env.__slash("/bf q mc 1")
    api.pump(env)
    T.has(sent(env), "wf bf q mc 1")
    api.tick(env, 2)
    env.__slash("/bf abandon")
    api.tick(env, 2)
    T.has(sent(env), "wf bf abandon")
end)

-- The site's Fight now: ?mode=boss&raid=<raid> -> the play page -> WenillaCore:Dispatch("BFH", raid)

T.test("Boss Fights: no window on arrival without the site's hint (duelers share the hangout)", function()
    local env = bf()
    connect(env, HI)
    api.tick(env, 2)
    T.ok(not env.BossFightsFrame or not env.BossFightsFrame:IsVisible(), "no window without a hint")
    T.ok(not string.find(sent(env), "bf mode boss", 1, true), "no mode change without a hint")
    T.ok(not string.find(sent(env), "bf go", 1, true), "no trip to Gurubashi without a hint")
end)

T.test("Boss Fights: the site's hint opens the Queue tab on that raid; in Boss Fights already, no trip", function()
    local env = bf()
    connect(env, HI)                                     -- hi says: in Boss Fights
    env.WenillaCore:Dispatch("BFH", "mc")
    api.tick(env, 2)
    T.shown(env.BossFightsFrame)
    T.eq(env.BossFights.pick.raid, "mc")
    T.has(texts(env), "Queue up")
    T.has(sent(env), "wf bf mode boss")
    T.ok(not string.find(sent(env), "bf go", 1, true), "already in Boss Fights: no go")
end)

T.test("Boss Fights: a hint before the realm's hello waits for it, then takes a dueler to Gurubashi, once", function()
    local env = bf()
    connect(env)
    env.OpenVanillaModeHint("boss", "onyxia")
    api.tick(env, 1)
    T.ok(not env.BossFightsFrame or not env.BossFightsFrame:IsVisible(), "nothing before the hello")
    T.ok(not string.find(sent(env), "bf mode boss", 1, true), "nothing sent before the hello")
    api.server_packet(env, "BF", "hi,1,0,,,0,onyxia:0:1:10;mc:0:1:10")    -- not in Boss Fights
    api.tick(env, 2)
    T.shown(env.BossFightsFrame)
    T.eq(env.BossFights.pick.raid, "onyxia")
    T.has(sent(env), "wf bf mode boss")
    T.has(sent(env), "wf bf go onyxia")
    local n = count(env, "bf mode boss")
    api.server_packet(env, "BF", "hi,1,1,onyxia,,0,onyxia:0:1:10;mc:0:1:10")
    api.tick(env, 2)
    T.eq(count(env, "bf mode boss"), n, "the hint applies once")
end)

T.test("Boss Fights: a realm that says the character is away from the hub gets sent there", function()
    local env = bf()
    connect(env, HI)
    env.WenillaCore:Dispatch("BFH", "any")
    api.tick(env, 2)
    T.ok(not string.find(sent(env), "bf go", 1, true), "in Boss Fights: no go yet")
    api.server_packet(env, "BF", "mode,1,0")
    api.tick(env, 2)
    T.has(sent(env), "wf bf go")
    -- other modes are Warfront's, not ours
    env.OpenVanillaModeHint("duels", "x")
    T.eq(env.BossFights.hint, nil)
end)
