-- Boss Fights: the window (Data/Interface/AddOns/BossFights), riding on Warfront's channel.
-- The server side is OpenVanilla/BossFights.cpp with realm/mangos/0027-openvanilla-bossfights.patch.
local T, api = ...

local function bf(opts)
    opts = opts or {}
    opts.latency = false
    opts.class = opts.class or "WARRIOR"
    opts.faction = opts.faction or "Horde"
    return T.addon("BossFights", opts)
end

local HI = "hi,1,1,onyxia,tank,2,onyxia:1:2:10;mc:0:1:10"

local function connect(env, hi)
    api.connect(env)
    api.tick(env, 1)
    api.server_packet(env, "WF", "1,0,0,0,0,1")
    api.pump(env)
    if hi then api.server_packet(env, "BF", hi) end
end

-- connect, then open the window as a player would (/bf): the realm's hello alone never opens it
local function open(env, hi)
    connect(env, hi)
    env.__slash("/bf")
    api.pump(env)
end

local function sent(env) return table.concat(env.__wnl, " | ") end
local function count(env, what)
    local n = 0
    for _, line in ipairs(env.__wnl) do if string.find(line, what, 1, true) then n = n + 1 end end
    return n
end
local function texts(env, f) return table.concat(api.visible_texts(env, f or env.BossFightsFrame), " | ") end

T.test("Boss Fights: asks the realm on Warfront's hello, and stays hidden where it's off", function()
    local env = bf()
    connect(env)
    T.has(sent(env), "wf bf hi")
    api.server_packet(env, "BF", "hi,0")
    T.ok(not env.BossFightsFrame or not env.BossFightsFrame:IsVisible(), "off: no window")
    env.__slash("/bf")
    T.has(api.chat_text(env), "Boss Fights realm only")
end)

T.test("Boss Fights: /bf opens the window, with the realm's raids and its tiers", function()
    local env = bf()
    open(env, HI)
    T.shown(env.BossFightsFrame)
    local t = texts(env)
    T.has(t, "Onyxia")
    T.has(t, "Molten Core")
    T.has(t, "Any raid")
    T.has(t, "T1")
    T.has(t, "cleared")          -- Onyxia tier 1
    T.has(t, "open")             -- tier 2
    T.has(t, "locked")           -- tiers 3 to 5
    T.has(t, "Going solo")
end)

T.test("Boss Fights: role, queue, the queue's state and leaving it", function()
