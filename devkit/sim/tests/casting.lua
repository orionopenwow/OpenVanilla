-- Casting (Castline): CL packets drive the target cast bar and nameplate bars.
local T, api = ...

local function bar(env) return env.Castline_TargetBar end
local function texts(env) return table.concat(api.visible_texts(env, env.Castline_TargetBar), " | ") end

T.test("Casting: a target cast fills, counts and fades out", function()
    local env = T.addon("Casting")
    api.set_target(env, { name = "Onyxia", hostile = true, level = -1 })
    api.server_packet(env, "CL", "target,Onyxia,Flame Breath,2000,0,Spell_Fire_Fire")
    T.shown(bar(env))
    T.has(texts(env), "Flame Breath")
    local cast = env.Castline.target
    T.eq(cast.icon, "Interface\\Icons\\Spell_Fire_Fire")
    T.no(cast.interruptible, "0 = cannot be interrupted")
    api.tick(env, 1)
    T.has(texts(env), "1.0s / 2.0s")
    api.tick(env, 1.6)                      -- dur + 0.5 passed: stops, then 0.6 s fade
    T.eq(env.Castline.target, nil)
    api.tick(env, 0.7)
    T.hidden(bar(env), "faded out")
end)

T.test("Casting: an interrupt turns the bar red and says Interrupted", function()
    local env = T.addon("Casting")
    api.server_packet(env, "CL", "target,Onyxia,Shadow Bolt,3000,1,Spell_Shadow_ShadowBolt")
    api.tick(env, 1)
    api.server_packet(env, "CL", "stop,target,Onyxia,1")
    T.has(texts(env), "Interrupted")
    T.eq(env.Castline.target, nil, "cast cleared")
    local sb = api.state(api.find_text(env, "Interrupted", bar(env))).parent
    local r, g = sb:GetStatusBarColor()
    T.near(r, 0.9, 1e-6, "red"); T.near(g, 0.14, 1e-6, "red")
    local lo, hi = sb:GetMinMaxValues()
    T.eq(sb:GetValue(), hi, "full bar")
    api.tick(env, 0.7)
    T.hidden(bar(env))
end)

T.test("Casting: channels count down; showTime / showIcon settings", function()
    local env = T.addon("Casting")
    env.ClassicPlus_Manager:SetSetting("Casting", "showTime", false)
    env.ClassicPlus_Manager:SetSetting("Casting", "showIcon", false)
    api.server_packet(env, "CL", "target,Kel'Thuzad,Arcane Missiles,5000,1,Spell_Nature_StarFall,1")
    T.ok(env.Castline.target.channel)
    api.tick(env, 1)
    local sb = api.state(api.find_text(env, "Arcane Missiles", bar(env))).parent
    T.near(sb:GetValue(), 4, 1e-6, "a channel's bar empties")
    T.lacks(texts(env), "s / ", "no time text")
end)

T.test("Casting: nameplate bars follow casts by caster name", function()
    local env = T.addon("Casting")
    local plate = api.add_nameplate(env, { name = "Defias Pillager", level = 15 })
    local other = api.add_nameplate(env, { name = "Defias Thug", level = 14 })
    api.server_packet(env, "CL", "plate,Defias Pillager,Fireball,3000,1,Spell_Fire_Fireball02")
    api.tick(env, 0.5)
    T.ok(plate.castline, "a bar was made for the casting plate")
    T.shown(plate.castline)
    T.eq(plate.castline.icon:GetTexture(), "Interface\\Icons\\Spell_Fire_Fireball02")
    T.eq(other.castline, nil)
    T.hidden(bar(env), "not our target")
    api.tick(env, 3)
    T.hidden(plate.castline, "cast over")
    env.ClassicPlus_Manager:SetSetting("Casting", "showNameplate", false)
    api.server_packet(env, "CL", "plate,Defias Pillager,Fireball,3000,1")
    api.tick(env, 0.5)
    T.hidden(plate.castline, "showNameplate off")
end)

T.test("Casting: /castline previews the bar; disabled addon shows nothing", function()
    local env = T.addon("Casting")
    env.__slash("/castline")
    T.shown(bar(env))
    T.has(texts(env), "Shadow Bolt")
    T.has(api.chat_text(env), "Casting preview")
    env.WenillaCore:SetAddonEnabled("Casting", false)
    T.hidden(bar(env))
    api.server_packet(env, "CL", "target,Onyxia,Flame Breath,2000,0")
    T.hidden(bar(env), "disabled")
end)

T.test("Casting: retargeting a caster shows that caster's spell", function()
        local env = T.addon("Casting")
        api.set_target(env, { name = "Onyxia", hostile = true })
        api.server_packet(env, "CL", "target,Onyxia,Flame Breath,2000,0,Spell_Fire_Fire")
        api.server_packet(env, "CL", "plate,Defias Pillager,Fireball,3000,1,Spell_Fire_Fireball02")
        api.tick(env, 0.2)
        api.set_target(env, { name = "Defias Pillager", hostile = true })
        T.eq(env.Castline.target.spell, "Fireball", "the cast state follows the new target")
        T.has(texts(env), "Fireball", "the bar should say what the new target casts")
    end)
