T.test("Core: stopping the demo keeps real server prices on a telemetry realm", function()
        local env = T.suite({ bags = { [0] = { size = 16, items = { { 2589, 20 } } } } })
        api.connect(env)
        api.on_server(env, "lg", function(id) api.server_packet(env, "LG", id .. ",1500,13,42") end)
        env.GameTooltip:SetBagItem(0, 1)
        api.pump(env)
        env.GameTooltip:SetBagItem(0, 1)
        T.has(api.tooltip_text(env), "Market (7d) x42", "real price before the demo")
        env.__slash("/wnl demo")
        api.tick(env, 1)
        env.__slash("/wnl demo")
        env.GameTooltip:SetBagItem(0, 1)
        api.pump(env)
        env.GameTooltip:SetBagItem(0, 1)
        T.has(api.tooltip_text(env), "Market (7d) x42", "real price after the demo")
    end)
