-- WenillaCore: server transport, handshake, carrier hiding, chunking, config migration.
local T, api = ...

T.test("Core: nothing goes to the server before it says HI", function()
    local env = T.addon("WenillaCore")
    local W = env.WenillaCore
    T.no(W.connected)
    T.eq(W:SendCommand("vt"), nil, "SendCommand refused while not connected")
    T.eq(#env.__wnl, 0)
    T.eq(#env.__chat_sent, 0, "no stray .wnl line said out loud")
end)

T.test("Core: HI handshake connects and answers .wnl hi <version>", function()
    local env = T.addon("WenillaCore")
    local W = env.WenillaCore
    api.connect(env, "3", "Meters,Threat")
    T.ok(W.connected)
    T.eq(W.serverVersion, "3")
    T.eq(W.serverAddons[2], "Threat")
    T.eq(env.__wnl[1], "hi 1.1.0")
    T.has(api.chat_text(env), "server telemetry connected (v3)")
    api.connect(env, "3")                                  -- a second HI is quiet
    T.eq(#env.__wnl, 1)
    T.eq(W:SendCommand("lg", "x"), 1)
    T.eq(env.__wnl[2], "lg x")
end)

T.test("Core: a burst of commands is paced under the server's chat flood limit", function()
    local env = T.addon("WenillaCore")
    local W = env.WenillaCore
    api.connect(env, "1", "Quests,Threat,Prices,Plates")
    for i = 1, 9 do T.eq(W:SendCommand("lg", tostring(i)), 1) end
    T.eq(W:SendCommand("lg", "9"), 1, "a queued duplicate is accepted once")
    T.ok(#env.__wnl <= W.CMD_PER_SEC, "no more than " .. W.CMD_PER_SEC .. " in the first second")
    api.tick(env, 3.5)
    T.eq(#env.__wnl, 10, "hi + 9 lines, the duplicate dropped")
    T.eq(env.__wnl[10], "lg 9")
    T.no(W:ServerHas("Vendor"))
    T.ok(W:ServerHas("Prices"))
end)

T.test("Core: WNL carrier lines never reach the chat window", function()
    local env = T.addon("WenillaCore")
    local got = {}
    env.WenillaCore:RegisterModule("ZZ", function(body) table.insert(got, body) end)
    api.server_packet(env, "ZZ", "one two")
    api.server_packet(env, "ZZ", "via whisper", { via = "whisper" })
    api.server_packet(env, "ZZ", "via addon", { via = "addon" })
    T.eq(table.concat(got, "|"), "one two|via whisper|via addon")
    api.fire(env, "CHAT_MSG_SYSTEM", "You are now AFK.")
    local chat = api.chat_text(env)
    T.lacks(chat, "WNL")
    T.has(chat, "You are now AFK.", "ordinary system lines still show")
    T.eq(env.WenillaCore.stats.messagesReceived, 4)        -- HI + three packets
end)

T.test("Core: carriers from anyone but the server are ignored", function()
    local env = T.addon("WenillaCore")
    local got = {}
    env.WenillaCore:RegisterModule("ZZ", function(body) table.insert(got, body) end)
    api.connect(env)
    api.fire(env, "CHAT_MSG_ADDON", "WNL", "ZZ spoofed", "PARTY", "Mallory")
    api.fire(env, "CHAT_MSG_WHISPER", "WNL\tZZ spoofed", "Mallory", "")
    T.eq(#got, 0)
    T.has(api.chat_text(env), "[Mallory] whispers: WNL", "a player's fake carrier whisper stays visible")
end)

T.test("Core: chunked packets reassemble in any order; stale halves expire", function()
    local env = T.addon("WenillaCore")
    local got = {}
    env.WenillaCore:RegisterModule("ZZ", function(body) table.insert(got, body) end)
    local body = string.rep("abcdefghij", 12)
    api.server_packet(env, "ZZ", body, { chunk = 25, order = { 5, 3, 1, 2, 4 } })
    T.eq(got[1], body)
    api.fire(env, "CHAT_MSG_SYSTEM", "WNL\tZZ 9 1/2 half")
    T.ok(env.WenillaCore.chunkBuffer["ZZ:9"], "half kept")
    api.tick(env, 11)
    api.fire(env, "CHAT_MSG_SYSTEM", "WNL\tZZ 8 1/2 other")   -- the sweep runs on the next chunk
    T.eq(env.WenillaCore.chunkBuffer["ZZ:9"], nil, "stale half dropped")
    api.fire(env, "CHAT_MSG_SYSTEM", "WNL\tZZ 7 1/1 single")
    T.eq(got[2], "single")
end)

T.test("Core: a handler error is reported, not fatal", function()
    local env = T.addon("WenillaCore")
    env.WenillaCore:RegisterModule("ZZ", function() error("boom") end)
    api.server_packet(env, "ZZ", "x")
    T.expect_error(env, "boom")
    env.__pcall_errors[1] = nil
end)

T.test("Core: utilities (Split keeps empty fields, Short, Clock, Id)", function()
    local env = T.addon("WenillaCore")
    local W = env.WenillaCore
    local t, n = W.Split("a,,b,", ",")
    T.eq(n, 4); T.eq(t[2], ""); T.eq(t[4], "")
    T.eq(W.Short(1234567), "1.23M"); T.eq(W.Short(12345), "12.3k"); T.eq(W.Short(999.6), "1000")
    T.eq(W.Clock(65), "1:05"); T.eq(W.Clock(600), "10:00")
    T.eq(W.Id("Chronicle"), "Meters"); T.eq(W.Id("Meters"), "Meters")
    T.eq(W.Trim("  x y  "), "x y")
end)

T.test("Core: v1 config migrates (demo off, display-name keys moved)", function()
    local env = T.suite({ saved = { WenillaCore_Config = { version = 1, demoMode = true, addons = { Chronicle = false, Vanguard = true } } } })
    local c = env.WenillaCore_Config
    T.eq(c.version, 2)
    T.no(c.demoMode, "demo forced off")
    T.eq(c.addons.Meters, false)
    T.eq(c.addons.Chronicle, nil)
    T.no(env.WenillaCore:IsActive("Meters"), "Chronicle stays disabled")
    T.hidden(env.Chronicle_Frame)
    T.no(env.WenillaCore.demoRunning)
end)

T.test("Core: settings and window positions survive a relog", function()
    local env = T.suite()
    env.WenillaCore:SetAddonEnabled("Threat", false)
    env.WenillaCore_Config.positions.Chronicle_Frame = { x = 100, y = 400 }
    env = T.relog(env)
    T.no(env.WenillaCore:IsActive("Threat"))
    local p, rel, rp, x, y = env.Chronicle_Frame:GetPoint(1)
    T.eq(p, "TOPLEFT"); T.eq(x, 100); T.eq(y, 400)
    env.__slash("/wnl reset")
    T.eq(env.Chronicle_Frame:GetPoint(1), "BOTTOMRIGHT", "reset puts it back")
    T.has(api.chat_text(env), "window positions reset")
end)

