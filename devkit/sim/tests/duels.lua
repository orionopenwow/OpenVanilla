    env.GetSpellName = function(i) local sp = spells[i]; if sp then return sp[1], sp[2] end end
    env.PickupSpell = function(i) local sp = spells[i]; env.__cursor = sp and sp[1]; env.__cursorRank = sp and sp[2] end
    api.fire(env, "LEARNED_SPELL_IN_TAB", 1)
    api.tick(env, 2)
    T.eq(env.__actionRanks[1], "Rank 11", "slot 1's Frostbolt is the best rank now")
