T.test("Duels Armory: a slot's items (worn first), search, wear one, and loadout codes put a whole set on", function()
    local env = duels({ class = "WARRIOR", faction = "Alliance" })
    api.add_item(env, 16477, { name = "Field Marshal's Plate Armor", quality = 4, icon = "Interface\\Icons\\INV_Chest_Plate04", equip = "INVTYPE_CHEST" })
    api.add_item(env, 16966, { name = "Breastplate of Wrath", quality = 4, icon = "Interface\\Icons\\INV_Chest_Plate16", equip = "INVTYPE_CHEST" })
    api.add_item(env, 21331, { name = "Conqueror's Breastplate", quality = 4, icon = "Interface\\Icons\\INV_Chest_Plate12", equip = "INVTYPE_CHEST" })
    api.add_item(env, 16478, { name = "Field Marshal's Plate Helm", quality = 4, icon = "Interface\\Icons\\INV_Helmet_05", equip = "INVTYPE_HEAD" })
    env.__inventory[5] = 16477
    connect(env, "1,2,0,0,1,1")
    local A = env.Duels.Armory
    env.__slash("/duels armory")
    T.shown(env.DuelsArmoryFrame)
    A.Pick(4)
    T.has(sent(env), "wf pool 4")
    api.server_packet(env, "WP", "4;16966,1;21331,3;16477,0")
    local items = A.Items()
    T.eq(items[1].id, 16477, "what you wear comes first")
    T.ok(items[1].worn)
    T.eq(items[2].id, 16966, "then unlocked (tier 1 <= your tier 2)")
    T.eq(items[3].id, 21331, "locked last (tier 3)")
    A.search = "wrath"
    T.eq(table.getn(A.Items()), 1, "search by name")
    A.search = ""
    A.onlyUnlocked = true
    T.eq(table.getn(A.Items()), 2, "unlocked only")
    A.onlyUnlocked = false
    A.Wear(items[2])
    T.has(sent(env), "wf slot 4 16966")
    local before = table.getn(env.__wnl)
    A.Wear(items[3])
    T.eq(table.getn(env.__wnl), before, "a locked item isn't asked for")
    -- codes
    local code = A.Encode({ [0] = 16478, [4] = 21331 })
    T.eq(string.sub(code, 1, 4), "OV1-")
    local back = A.Decode(code)
    T.eq(back[0], 16478); T.eq(back[4], 21331); T.eq(back[1], nil)
    T.eq(A.Decode("hello"), nil, "not a code")
    T.eq(A.Decode("OV1-1-2"), nil, "too short")
    T.ok(A.Apply(code))
    api.tick(env, 1)
    T.has(sent(env), "wf slot 0 16478", "one slot at a time")
    T.ok(not string.find(sent(env), "wf slot 4 21331", 1, true), "the next waits for the answer")
    api.server_packet(env, "WS", "ok,0,16478")
    api.tick(env, 1)
    T.has(sent(env), "wf slot 4 21331", "then the next")
    api.server_packet(env, "WS", "ok,4,21331")
    T.eq(A.queue, nil, "done")
    local name = A.Save()
    T.eq(env.DuelsLoadouts[1].name, name)
    T.has(env.DuelsLoadouts[1].code, "OV1-")
end)

