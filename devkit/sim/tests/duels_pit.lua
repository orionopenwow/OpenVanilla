-- Duels: the pit (Data/Interface/AddOns/Duels/Pit.lua): the arrival, the announcer, the opponent card,
-- the countdown, the result card, the tracker (winner stays on), the brawl, challenges and the cup.
-- The server side is OpenVanilla/DuelsPit.cpp (realm/mangos/0061-openvanilla-duels-pit.patch).
local T, api = ...

local function duels(opts)
    opts = opts or {}
    opts.latency = false
    opts.class = opts.class or "ROGUE"
    opts.faction = opts.faction or "Horde"
    opts.name = opts.name or "Kaelix"
    return T.addon("Duels", opts)
end

-- a Duels realm in Lite (hello field 7), and the pit's first answer
local function arrive(env, dp)
    api.connect(env)
    api.tick(env, 1)
    api.server_packet(env, "WF", "1,3,0,0,1,1,1")
    api.pump(env)
    api.tick(env, 3)
    api.pump(env)
    api.server_packet(env, "DP", dp or "4,2,1,3,6,0,0,,0,0,0,600,closed:90000,1,100")
end

local function sent(env) return table.concat(env.__wnl, " | ") end
local function screen(env) return table.concat(api.visible_texts(env), " | ") end
local function count(env, line)
    local n = 0
    for _, l in ipairs(env.__wnl) do if l == line then n = n + 1 end end
    return n
end

T.test("Pit: the realm's hello asks for the pit; no pit, no tracker", function()
    local env = duels()
    api.connect(env)
    api.tick(env, 1)
    api.server_packet(env, "WF", "1,3,0,0,1,1,1")
    api.pump(env)
    T.ok(not string.find(sent(env), "pit info", 1, true), "not with the hello's own requests")
    api.tick(env, 3)
    api.pump(env)
    T.has(sent(env), "wf pit info")
    api.server_packet(env, "DP", "off")
    T.ok(not env.DuelsPitTracker or not env.DuelsPitTracker:IsVisible(), "no pit: no tracker")
    T.ok(not env.DuelsPitBanner or not env.DuelsPitBanner:IsVisible(), "and no arrival card")
    env.__slash("/duels line")
    T.has(api.chat_text(env), "No pit on this realm")
end)

