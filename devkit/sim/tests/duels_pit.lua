    T.shown(env.DuelsPitCard)
    local c = table.concat(api.visible_texts(env, env.DuelsPitCard), " | ")
    T.has(c, "Morva")
    T.has(c, "Undead Mage, level 60")
    T.has(c, "Cup Champion")
    T.has(c, "12 won, 3 lost")
