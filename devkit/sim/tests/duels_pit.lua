T.test("Pit: malformed and empty lines never raise", function()
    local env = duels()
    arrive(env)
    for _, tag in ipairs({ "DA", "DL", "DO", "DC", "DR", "DP", "DB", "DX", "DU" }) do
        for _, body in ipairs({ "", ",", ",,,,,,,,,,,,,,", ";;;", "win", "brawl", "cup", "err", "brawl,soon", "cup,fight", "ok", "joined" }) do
            api.server_packet(env, tag, body)
        end
    end
    api.tick(env, 30)
    T.eq(table.getn(env.__errors), 0, table.concat(env.__errors, "\n"))
end)
