    api.enter(B.Concord_Card1)
    T.has(api.tooltip_text(B), "Thursday. We raid on Tuesday and Thursday.")
    local r, g = B.Concord_Card1.chips[2].text:GetTextColor()
    T.ok(r < 1, "level 60 meets the minimum: the level chip is not red")
end)

T.test("Guilds: without the Guilds_* art the window uses stock icons", function()
    local B = T.addon("Guilds", { name = "Berra", level = 12, art = false })
    api.tick(B, 7)
    B.__slash("/guilds")
    T.lacks(B.Concord_Frame.portrait:GetTexture() or "", "Guilds_", "portrait falls back to a stock icon")
    T.eq(B.Concord_EmptyArt:GetTexture(), "Interface\\Icons\\INV_Shirt_GuildTabard_01")
    api.server_packet(B, "CO", "L~Silver Hand~Raiding~58~45~Onyxia~Kael;L~Night Owls~Casual~1~0~Late~Owl")
    api.tick(B, 1)
    for i = 1, 2 do
        local c = B["Concord_Card" .. i]
        T.shown(c)
        T.has(c.crest:GetTexture(), "Interface\\Icons\\")
        T.shown(c.edge, "stock icon sits in a thin edge")
    end
    local byName = {}
    for i = 1, 2 do byName[B["Concord_Card" .. i].name:GetText()] = B["Concord_Card" .. i] end
    T.eq(byName["<Night Owls>"].crest:GetTexture(), "Interface\\Icons\\INV_Misc_PocketWatch_01")
    T.eq(byName["<Silver Hand>"].crest:GetTexture(), "Interface\\Icons\\Ability_Warrior_BattleShout")
    api.click(byName["<Silver Hand>"].apply)
    T.eq(B.__popups[1].text, "Whisper Kael to ask about joining <Silver Hand>?")
end)

T.test("Guilds: a right-click on the Guild chat tab opens its menu; only Hide this tab hides it", function()
    local env = T.addon("Guilds")
    api.click(env.ChatFrame_GuildTab, "RightButton")
    T.shown(env.WenillaCore_Menu)
    T.ok(env.WenillaCore:Settings("Guilds").showChatTab ~= false, "a stray right-click no longer hides the tab")
    api.click_text(env, "Hide this tab", env.WenillaCore_Menu)
    T.eq(env.WenillaCore:Settings("Guilds").showChatTab, false)
    T.has(api.chat_text(env), "Guild tab hidden")
end)
