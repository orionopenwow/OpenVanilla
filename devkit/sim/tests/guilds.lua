-- Guilds (Concord): listings over the hidden CPConcord channel between two clients, the apply
-- whisper, CO server packets, focus tabs, search, scrolling and expiry; the Guild Finder window
-- (Classic frame, listing cards, empty state) with and without the Guilds_* art.
local T, api = ...

local function two()
    local A = T.addon("Guilds", { name = "Aldric", class = "WARRIOR", level = 60, guild = { name = "Ashen Vanguard", members = 38 } })
    local B = T.addon("Guilds", { name = "Berra", class = "HUNTER", level = 12 })
    api.tick(A, 7)                          -- both join CPConcord 6 s after entering the world
    return A, B
end

local function tab(env, key) api.click(env.Concord_Frame.tabs:Button(key)) end

local function post(A, level, pitch)
    A.__slash("/guilds")
    tab(A, "mine")
    T.shown(A.Concord_PostForm, "post form")
    api.type(A.Concord_PostLevel, level)
    api.type(A.Concord_PostPitch, pitch)
    api.click(api.find_button(A, "Post"))
    api.pump(A)
end

T.test("Guilds: a listing travels to another client and the apply whisper comes back", function()
    local A, B = two()
    T.eq(A.GetChannelName("CPConcord") > 0, true, "A joined the hidden channel")
    T.eq(B.GetChannelName("CPConcord") > 0, true, "B joined the hidden channel")
    post(A, "40", "Molten Core Tue/Thu 8pm | need healers ~ and a warlock")
    T.has(api.chat_text(B), "[Guilds] <Ashen Vanguard> is recruiting (Raiding): Molten Core Tue/Thu 8pm - need healers - and a warlock")
    B.__slash("/concord")
    T.shown(B.Concord_Card1)
    local c = B.Concord_Card1
    T.eq(c.name:GetText(), "<Ashen Vanguard>")
    T.has(c.crest:GetTexture(), "Guilds_Focus_Raiding", "focus crest art")
    T.hidden(c.edge, "no stock-icon edge around the crest art")
    T.eq(c.chips[1].text:GetText(), "Raiding")
    T.eq(c.chips[2].text:GetText(), "Level 40+")
    T.eq(c.chips[3].text:GetText(), "38 members")
    T.eq(c.pitch:GetText(), "Molten Core Tue/Thu 8pm - need healers - and a warlock")
    local r = c.chips[2].text:GetTextColor()
    T.eq(r, 1, "level 12 is under the minimum: the level chip is red")
    T.shown(c.apply)
    T.hidden(B.Concord_Card2)
    T.ok(api.screen_has(B, "1 guild recruiting", B.Concord_Frame), "count text")
    T.no(B.Concord_Frame.tabs:Button("mine"), "not in a guild: no My listing tab")
    api.enter(c)
    T.has(api.tooltip_text(B), "Posted by Aldric. Click to apply.")
    T.has(api.tooltip_text(B), "They ask for level 40 or higher.")
    api.click(c.apply)
    T.eq(B.__popups[1].text, "Whisper Aldric to ask about joining <Ashen Vanguard>?")
    api.popup_click(B, "CONCORD_APPLY", 1)
    api.pump(B)
    T.has(api.chat_text(A), "[Berra] whispers: [Guilds] Hi! I'd like to join <Ashen Vanguard>. Level 12 hunter.")
    -- the carrier channel never shows in either chat window
    T.lacks(api.chat_text(A), "CPConcord")
    T.lacks(api.chat_text(B), "CPConcord")
    T.lacks(api.chat_text(B), "CO1~")
end)

T.test("Guilds: the poster's own card cannot be applied to; Edit and Remove", function()
    local A, B = two()
    post(A, "1", "Friendly levelling guild")
    T.shown(A.Concord_Card1)
    T.hidden(A.Concord_Card1.apply, "no Apply on your own card")
    T.shown(A.Concord_Card1.mine)
    api.click(A.Concord_Card1)
    T.eq(#A.__popups, 0, "no popup for your own listing")
    tab(A, "mine")
    T.eq(A.Concord_PostPitch:GetText(), "Friendly levelling guild", "form remembers the post")
    T.ok(api.screen_has(A, "Listed on the board", A.Concord_Frame))
    api.click(api.find_button(A, "Remove"))
    T.hidden(A.Concord_Card1)
    T.eq(A.WenillaCore_Config.concord.Aldric, nil)
end)

T.test("Guilds: Refresh asks who is recruiting and listers answer after a pause", function()
    local A, B = two()
    post(A, "40", "Raids")
    local sent = #A.__chat_sent
    api.tick(A, 61)
    B.__slash("/guilds")
    api.click(api.find_button(B, "Refresh"))
    api.tick(A, 11)
    T.eq(#A.__chat_sent, sent + 1, "A re-sent its listing")
    T.eq(B.__bus.log[#B.__bus.log].from, "Aldric")
end)

T.test("Guilds: CO server listings, announcements, filter, scroll and expiry", function()
    local A, B = two()
    post(A, "40", "Raids")
    api.tick(B, 1)
    api.server_packet(B, "CO", "L~Silver Hand~Raiding~58~45~Onyxia and BWL~Kael;L~Hearth and Home~Social~1~91~Chill;"
        .. "L~Blood and Thunder~PvP~40~22~Premades;L~Stormwind Watch~Leveling~1~64~Dungeons;L~Night Owls~Casual~1~0~Late;bad~row")
    api.server_packet(B, "CO", "announcement,Guild fair Saturday in Goldshire")
    T.has(api.chat_text(B), "[Guilds] Guild fair Saturday in Goldshire")
    B.__slash("/guilds")
    T.ok(api.screen_has(B, "6 guilds", B.Concord_Frame))
    T.eq(B.Concord_Card4.name:GetText() ~= nil, true, "four cards filled")
    T.ok(B.Concord.listings["Night Owls"], "server listing stored")
    T.eq(B.Concord.listings["Night Owls"].poster, nil, "server listings carry no poster unless given")
    T.eq(B.Concord.listings["Silver Hand"].poster, "Kael")
    local before = { B.Concord_Card1.name:GetText(), B.Concord_Card2.name:GetText() }
    api.wheel(B.Concord_Frame, -1)
    T.eq(B.Concord_Card1.name:GetText(), before[2], "scrolled one card")
    api.wheel(B.Concord_Frame, -5)
    T.eq(B.Concord.scroll, 1, "scroll clamps at the end (five cards show)")
    tab(B, "Raiding")
    T.ok(api.screen_has(B, "2 guilds recruiting", B.Concord_Frame))
    T.eq(B.Concord.scroll, 0, "a new tab starts at the top")
    for i = 1, 2 do T.eq(B["Concord_Card" .. i].chips[1].text:GetText(), "Raiding") end
    T.hidden(B.Concord_Card3)
    tab(B, "Casual")
    T.eq(B.Concord_Card1.name:GetText(), "<Night Owls>")
    T.hidden(B.Concord_Card1.chips[3], "no member count, no chip")
    T.no(B.Concord_Card1.apply:IsEnabled(), "a realm listing without a poster cannot be applied to")
    tab(B, "Any")
    T.ok(api.screen_has(B, "6 guilds recruiting", B.Concord_Frame))
    -- server listings are not re-sent and expire after 25 minutes; Aldric re-posts every 10
    api.tick(B, 1520, 2)
    tab(B, "Raiding"); tab(B, "Any")
    T.ok(api.screen_has(B, "1 guild recruiting", B.Concord_Frame), "only the live listing is left")
    T.eq(B.Concord_Card1.name:GetText(), "<Ashen Vanguard>")
end)

T.test("Guilds: chat tab follows the chat tabs and the setting", function()
    local A = T.addon("Guilds", { name = "Aldric", guild = { name = "Ashen Vanguard" } })
    api.tick(A, 1)
    T.shown(A.ChatFrame_GuildTab)
    T.eq(A.ChatFrame_GuildTab:GetAlpha(), 1, "visible while the chat tab is")
    api.click(A.ChatFrame_GuildTab, nil, true)
    T.shown(A.Concord_Frame, "the tab opens the board")
    A.ChatFrame1Tab:SetAlpha(0)
    api.tick(A, 0.2)
    T.eq(A.ChatFrame_GuildTab:GetAlpha(), 0, "fades with the chat tab")
    A.ClassicPlus_Manager:SetSetting("Guilds", "showChatTab", false)
    T.hidden(A.ChatFrame_GuildTab)
    A.WenillaCore:SetAddonEnabled("Guilds", false)
    T.hidden(A.Concord_Frame, "disabling closes the board")
end)

T.test("Guilds: text from other players is shown literally (no colour codes or links)", function()
        local A, B = two()
        -- a modified client can put valid escapes in a listing; a stock Concord client never would
        A.SendChatMessage("CO1~L~Ashen Vanguard~Raiding~40~38~|cffff0000[Raid Warning]|r free epics at the bank",
            "CHANNEL", nil, A.GetChannelName("CPConcord"))
        api.pump(A)
        local raw = B.__chat[#B.__chat]
        T.has(raw, "[Raid Warning]")
        -- escaped as "||cff..." (shown literally); an unescaped "|c" would colour the line
        T.ok(not string.find(" " .. raw, "[^|]|cffff0000"), "colour code from another player reached the chat window")
    end)


T.test("Guilds: the Guild Finder is the Classic frame with a crest portrait and focus tabs", function()
    local A = T.addon("Guilds", { name = "Aldric", level = 60, guild = { name = "Ashen Vanguard", members = 38 } })
    api.tick(A, 7)
    A.__slash("/guilds")
    local f = A.Concord_Frame
    T.ok(f.classic, "UI.ClassicFrame")
    T.eq(f.title:GetText(), "Guild Finder")
    T.has(f.portrait:GetTexture(), "Guilds_Portrait")
    local keys = {}
    for _, t in ipairs(f.tabs.tabs) do table.insert(keys, t.label) end
    T.eq(table.concat(keys, ","), "All,Raiding,Leveling,PvP,Social,Casual,My listing")
    T.eq(f.tabs:Selected(), "Any")
    T.shown(A.Concord_Search)
    T.ok(api.find_button(A, "Refresh"), "Refresh in the header band")
    -- My listing: the focus crests pick the focus, the preview card follows the form
    tab(A, "mine")
    T.shown(A.Concord_PostForm)
    T.hidden(A.Concord_ListPage)
    T.has(A.Concord_PostFocus1.icon:GetTexture(), "Guilds_Focus_Raiding")
    T.shown(A.Concord_PostFocus1.glow, "Raiding is the default focus")
    api.click(A.Concord_PostFocus3)
    T.shown(A.Concord_PostFocus3.glow)
    T.hidden(A.Concord_PostFocus1.glow)
    api.type(A.Concord_PostPitch, "Battlegrounds every night")
    T.eq(A.Concord_PostPreview.chips[1].text:GetText(), "PvP")
    T.eq(A.Concord_PostPreview.pitch:GetText(), "Battlegrounds every night")
    T.has(A.Concord_PostPreview.crest:GetTexture(), "Guilds_Focus_PvP")
    T.ok(api.screen_has(A, "Not listed yet", f))
    T.hidden(api.find_button(A, "Remove"), "nothing to remove yet")
    api.click(api.find_button(A, "Post"))
    T.shown(A.Concord_ListPage, "posting goes back to the list")
    T.eq(A.WenillaCore_Config.concord.Aldric.focus, "PvP")
    T.has(A.Concord_Card1.crest:GetTexture(), "Guilds_Focus_PvP")
end)

T.test("Guilds: search filters by name and pitch; empty states have an emblem and a hint", function()
    local B = T.addon("Guilds", { name = "Berra", class = "HUNTER", level = 12 })
    api.tick(B, 7)
    B.__slash("/guilds")
    T.ok(api.screen_has(B, "No guilds are recruiting right now", B.Concord_Frame))
    T.ok(api.screen_has(B, "Listings appear here as guilds post them", B.Concord_Frame))
    T.shown(B.Concord_EmptyArt, "the round emblem above the empty line")
    T.has(B.Concord_EmptyArt:GetTexture(), "Guilds_Portrait")
    T.shown(B.Concord.ui.emptyRing)
    api.server_packet(B, "CO", "L~Silver Hand~Raiding~58~45~Onyxia and BWL~Kael;L~Hearth and Home~Social~1~91~Chill evenings by the fire~Mara;"
        .. "L~Stormwind Watch~Leveling~1~64~Dungeons and quests~Rook")
    api.tick(B, 1)
    T.hidden(B.Concord_EmptyArt)
    T.ok(api.screen_has(B, "3 guilds recruiting", B.Concord_Frame))
    api.type(B.Concord_Search, "ONYXIA")
    T.ok(api.screen_has(B, "1 guild found", B.Concord_Frame), "matches the pitch, any case")
    T.eq(B.Concord_Card1.name:GetText(), "<Silver Hand>")
    api.type(B.Concord_Search, "hearth")
    T.eq(B.Concord_Card1.name:GetText(), "<Hearth and Home>", "matches the name")
    T.has(B.Concord_Card1.crest:GetTexture(), "Guilds_Focus_Social")
    api.type(B.Concord_Search, "zeppelin")
    T.ok(api.screen_has(B, "No guilds match \"zeppelin\"", B.Concord_Frame))
    T.shown(B.Concord_EmptyArt)
    api.type(B.Concord_Search, "")
    tab(B, "PvP")
    T.ok(api.screen_has(B, "No PvP guilds are recruiting right now", B.Concord_Frame))
    tab(B, "Any")
    api.enter(B.Concord_Card1)
    T.has(api.tooltip_text(B), "Posted by")
end)

T.test("Guilds: long pitches are cut to two lines on the card and shown whole in the tooltip", function()
    local B = T.addon("Guilds", { name = "Berra", level = 60 })
    api.tick(B, 7)
    local long = string.rep("We raid on Tuesday and Thursday. ", 5)
    api.server_packet(B, "CO", "L~Long Winded~Raiding~1~10~" .. long .. "~Kael")
    B.__slash("/guilds")
    local text = B.Concord_Card1.pitch:GetText()
