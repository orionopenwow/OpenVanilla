-- Right-click unit menus: the UI Repack's unit frames, nameplates and chat names
-- (WenillaCore/UnitMenu.lua, Repack/Elv.lua).
local T, api = ...

local function repack(opts)
    local env = T.client(opts)
    api.load_with_deps(env, "Repack")
    api.load_with_deps(env, "Persona")
    api.login(env)
    env.ClassicPlusUI.Elv:Apply()
    return env
end

local function texts(env) return "," .. table.concat(api.menu_texts(env), ",") .. "," end

T.test("Menus: the Repack player frame opens your own menu (SELF)", function()
    local env = repack()
    T.ok(env.CPElvPlayer, "the Repack's player frame")
    api.click(env.CPElvPlayer, "RightButton")
    local m = api.menu(env)
    T.ok(m, "a menu opened")
    T.eq(m.name, "ClassicPlusUnitDropDown", "our own dropdown, not the stock PlayerFrameDropDown")
    local t = texts(env)
    T.has(t, ",Herald,", "titled with your name")
    T.has(t, ",Raid Target Icon,")
    T.has(t, ",View Persona,", "Persona's entry")
    T.has(t, ",Cancel,")
    T.lacks(t, ",Whisper,", "no whispering yourself")
    -- the same click again closes it, as the stock frames do
    api.click(env.CPElvPlayer, "RightButton")
    T.no(api.menu(env))
end)

T.test("Menus: the Repack target frame: a player gets PLAYER, an NPC gets the target menu", function()
    local env = repack()
    local ann = T.client({ name = "Ann", class = "MAGE" })
    api.set_target(env, "Ann")
    api.click(env.CPElvTarget, "RightButton")
    local t = texts(env)
    T.has(t, ",Ann,"); T.has(t, ",Whisper,"); T.has(t, ",Inspect,"); T.has(t, ",Invite,")
    T.has(t, ",View Persona,"); T.has(t, ",Cancel,")
    api.menu_click(env, "Whisper")
    T.eq(env.__unitpopup_clicked, "WHISPER", "the stock handler runs")
    T.eq(env.__opened_chat[1], "/w Ann ")
    api.set_target(env, { name = "Hogger", isPlayer = false, hostile = true })
    api.click(env.CPElvTarget, "RightButton")
    t = texts(env)
    T.has(t, ",Hogger,"); T.has(t, ",Raid Target Icon,"); T.has(t, ",Cancel,")
    T.lacks(t, ",Whisper,")
    T.eq(env.WenillaCore.UnitMenu.Which("target"), "TARGET")
    T.ok(ann)
end)

T.test("Menus: party frames get PARTY; raid members RAID_PLAYER; your pet PET", function()
    local env = repack()
    local bo = T.client({ name = "Bo", class = "PRIEST" })
    api.group({ env, bo }, "party")
    api.click(env.CPElvParty1, "RightButton")
    local t = texts(env)
    T.has(t, ",Bo,"); T.has(t, ",Whisper,"); T.has(t, ",Inspect,"); T.has(t, ",View Persona,"); T.has(t, ",Cancel,")
    T.lacks(t, ",Invite,", "already in your party")
    T.eq(env.WenillaCore.UnitMenu.Which("party1"), "PARTY")
    api.menu_click(env, "View Persona")
    T.shown(env.PersonaFrame, "Persona's profile window")
    T.eq(env.Persona.viewing, "Bo", "for Bo")
    local raid = T.client({ name = "Cy" })
    api.group({ env, bo, raid }, "raid")
    T.eq(env.WenillaCore.UnitMenu.Which("raid2"), "RAID_PLAYER")
    env.WenillaCore.UnitMenu.Open("raid2")
    t = texts(env)
    T.has(t, ",Whisper,"); T.has(t, ",Promote to Assistant,"); T.has(t, ",View Persona,"); T.has(t, ",Cancel,")
    env.__units.pet = { name = "Wolfie", class = "WARRIOR", level = 20, isPlayer = false, debuffs = {}, buffs = {} }
    env.TargetUnit("pet")
    api.click(env.CPElvTarget, "RightButton")
    T.eq(env.WenillaCore.UnitMenu.Which("target"), "PET")
    t = texts(env)
    T.has(t, ",Wolfie,"); T.has(t, ",Pet Info,"); T.has(t, ",Dismiss Pet,"); T.has(t, ",Cancel,")
end)

T.test("Menus: right-clicking a chat name opens the FRIEND menu (stock path)", function()
    local env = repack()
    api.right_click_name(env, "Bob")
    local m = api.menu(env)
    T.ok(m, "menu shown")
    T.eq(m.name, "FriendsDropDown", "FriendsFrame.xml's dropdown when it is there")
    local t = texts(env)
    T.has(t, ",Bob,"); T.has(t, ",Whisper,"); T.has(t, ",Invite,"); T.has(t, ",Target,"); T.has(t, ",Cancel,")
    T.has(t, ",View Persona,")
    api.menu_click(env, "Invite")
    T.eq(env.__invites and env.__invites[1], "Bob")
end)

T.test("Menus: without FriendsFrame's dropdown the chat-name menu still opens (ours)", function()
    local env = repack()
    env.FriendsDropDown = nil
    rawset(env, "FriendsDropDown", false)
    api.right_click_name(env, "Bob")
    local m = api.menu(env)
    T.ok(m, "menu shown")
    T.eq(m.name, "ClassicPlusUnitDropDown")
    local t = texts(env)
    T.has(t, ",Bob,"); T.has(t, ",Whisper,"); T.has(t, ",Invite,"); T.has(t, ",Target,"); T.has(t, ",Cancel,")
    api.menu_click(env, "Target")
    T.eq(env.__unitpopup_clicked, "TARGET")
end)

T.test("Menus: works with just WenillaCore (no Repack) for any unit token", function()
    local env = T.addon("WenillaCore")
    local ann = T.client({ name = "Ann" })
    api.set_target(env, "Ann")
    T.ok(env.WenillaCore.UnitMenu.Open("target"))
    local t = texts(env)
    T.has(t, ",Whisper,"); T.has(t, ",Invite,"); T.has(t, ",Cancel,")
    T.no(env.WenillaCore.UnitMenu.Open("focus"), "no such unit: nothing opens")
    T.ok(ann)
end)
