-- Plates (Visage): restyled nameplates, the level cap, clicking plates, the target's debuffs
-- and VS debuff timers.
local T, api = ...
local function W_P(env) return env.Visage end

local SWP = "Interface\\Icons\\Spell_Shadow_ShadowWordPain"
local GAR = "Interface\\Icons\\Ability_Rogue_Garrote"

-- Idle plates (out of combat, not the target) are hidden by default; most tests here click and fade
-- plates, so they run with that off. opts.hideIdle = true keeps the shipped default.
local function visage(opts)
    opts = opts or {}
    if not opts.hideIdle and opts.saved == nil then
        opts.saved = { WenillaCore_Config = { version = 1, settings = { Plates = { hideIdle = false } } } }
    end
    return T.addon("Plates", opts)
end

local function target(env, health)
    api.set_target(env, { name = "Defias Thug", hostile = true, isPlayer = false, level = 14, health = health or 100,
        debuffs = { { SWP, 1, "Magic" }, { GAR, 3 } } })
end

T.test("Plates: new nameplates get the stock-shaped grey frame over the bar, the level in its grey box", function()
    local env = visage({ level = 11 })
    local p = api.add_nameplate(env, { name = "Defias Thug", level = 14 })
    api.tick(env, 0.3)
    local v = p.visage
    T.ok(v, "styled")
    T.shown(v.case, "dark case behind the health bar")
    T.eq(v.borderTex:GetAlpha(), 0, "stock border hidden")
    T.shown(v.cap, "the cap")
    -- the frame: three slices of Plate_Frame (fixed ends, stretched middle) over the bar
    T.eq(table.getn(v.frame), 3)
    for i = 1, 3 do T.has(v.frame[i]:GetTexture(), "Plate_Frame", "frame art " .. i) end
    T.eq(v.frameArt, W_P(env).FRAME_OURS)
    T.ok(v.rim:GetFrameLevel() > p:GetChildren():GetFrameLevel(), "frame above the bar: its round lip covers the bar's square ends")
    local hb = p:GetChildren()
    local sc = ((hb:GetHeight() or 0) > 0 and hb:GetHeight() or 10) / 10
    local a, rel, b, x, y = v.frame[1]:GetPoint(1)
    T.eq(rel, hb); T.eq(a .. " " .. b, "TOPLEFT TOPLEFT")
    T.near(x, -3 * sc, 1e-6, "the round left end reaches 3 art px past the bar"); T.near(y, 3 * sc, 1e-6)
    local _, rrel, rb, rx = v.frame[3]:GetPoint(2)
    T.eq(rrel, hb); T.eq(rb, "BOTTOMRIGHT"); T.near(rx, 32 * sc, 1e-6, "the right end with the level box")
    local ca, crel, cb, cx = v.cap:GetPoint(1)
    T.eq(crel, hb); T.eq(ca .. " " .. cb, "TOPLEFT TOPRIGHT"); T.near(cx, 3 * sc, 1e-6, "the number sits in the grey box")
    T.eq(v.capText:GetText(), "14")
    T.eq(select(2, v.capText:GetPoint(1)), v.cap, "the number sits in the cap")
    local _, _, _, level = p:GetRegions()
    T.eq(level:GetAlpha(), 0, "the floating stock number is hidden")
    local r, g, b = v.capText:GetTextColor()
    T.eq(r, 1); T.eq(g, 0.5, "three levels above you: orange"); T.eq(b, 0.25)
    env.ClassicPlus_Manager:SetSetting("Plates", "levelDifficulty", false)
    api.tick(env, 0.3)
    local r2, g2, b2 = v.capText:GetTextColor()
    T.eq(r2 .. "," .. g2 .. "," .. b2, "1,0.82,0", "setting off: always gold-yellow")
    env.__slash("/visage")
    T.has(api.chat_text(env), "Plates: styling 1 nameplate.")
end)

