-- -- Placement: lift, stacking, focus, compact ---------------------------------------------
-- api.place_nameplate seats a plate like the engine: its TOP centre on the head point.

local function hbY(p) local a, rel, b, _, y = p:GetChildren():GetPoint(1); return y, a, rel, b end

T.test("Plates: the bar is lifted above the plate's head anchor, name and click area with it", function()
    local env = visage()
    local p = api.place_nameplate(env, api.add_nameplate(env, { name = "Young Thistle Boar", level = 2 }), 400, 300)
    api.tick(env, 0.3)
    local hb = p:GetChildren()
    local y, a, rel, b = hbY(p)
    T.eq(a .. " " .. b, "BOTTOM TOP", "the bar's bottom hangs off the plate's top (the head point)")
    T.eq(rel, p)
    T.eq(y, 8, "default lift: 8 px above it, clear of the model")
    local _, _, name = p:GetRegions()
    local na, nrel, nb = name:GetPoint(1)
    T.eq(na .. " " .. nb, "BOTTOM TOP"); T.eq(nrel, hb, "the name rides on the bar")
    T.eq(select(2, p.visage.click:GetPoint(1)), p.visage.case, "the click area follows the pill")
    T.eq(select(2, p.visage.case:GetPoint(1)), p.visage.frame[1], "the case is the frame's outline")
    T.eq(select(2, p.visage.frame[1]:GetPoint(1)), hb, "and the frame rides on the bar")
    env.ClassicPlus_Manager:SetSetting("Plates", "lift", 20)
    api.tick(env, 0.3)
    T.eq(hbY(p), 20, "the lift setting moves it")
end)

T.test("Plates: overlapping plates stack upward; the lower (nearer) one keeps its spot", function()
    local env = visage()
    local near = api.place_nameplate(env, api.add_nameplate(env, { name = "Boar A" }), 400, 300)
    local far = api.place_nameplate(env, api.add_nameplate(env, { name = "Boar B" }), 430, 310)
    local away = api.place_nameplate(env, api.add_nameplate(env, { name = "Boar C" }), 800, 300)
    api.tick(env, 1)
    T.eq(hbY(near), 8, "nearer plate (lower on screen) is not moved")
    T.eq(hbY(away), 8, "a plate off to the side is not moved")
    -- bar (slim at full health) + case padding + name gap + name
    local pill = near:GetChildren():GetHeight() + 8 + 4 + 13
    -- far's pill must start above near's: 300 + 8 - 4 + pill + 1 = far.top + lift' - 4
    T.eq(hbY(far), 300 + pill + 1 - 310 + 8, "pushed just clear of the nearer plate")
    T.ok(far.visage.nudge > 0)
    -- far moves away: it settles back down smoothly, not in one jump
    api.place_nameplate(env, far, 600, 310)
    api.tick(env, 0.1)
    local mid = hbY(far)
    T.ok(mid > 8 and mid < 300 + pill + 1 - 310 + 8, "eases back (" .. tostring(mid) .. ")")
    api.tick(env, 1)
    T.eq(hbY(far), 8, "back home once clear")
end)

T.test("Plates: no jitter: stacked positions hold steady while nothing moves", function()
    local env = visage()
    local a = api.place_nameplate(env, api.add_nameplate(env, { name = "A" }), 400, 300)
    local b = api.place_nameplate(env, api.add_nameplate(env, { name = "B" }), 410, 302)
    local c = api.place_nameplate(env, api.add_nameplate(env, { name = "C" }), 420, 304)
    api.tick(env, 1.5)
    local ya, yb, yc = hbY(a), hbY(b), hbY(c)
    T.ok(yb > ya and yc > yb, "a stack of three")
    for _ = 1, 20 do
        api.tick(env, 0.1)
        T.eq(hbY(a), ya); T.eq(hbY(b), yb); T.eq(hbY(c), yc)
    end
    -- a 1 px wobble of the bottom plate does not make the stack swap order
    api.place_nameplate(env, b, 410, 299.5)
    api.tick(env, 1)
    T.eq(hbY(a), ya, "the stacked order is sticky")
end)

T.test("Plates: the target's plate stays bright and on top; the others fade", function()
    local env = visage()
    local foe = api.place_nameplate(env, api.add_nameplate(env, { name = "Defias Thug" }), 400, 300)
    local other = api.place_nameplate(env, api.add_nameplate(env, { name = "Kobold" }), 600, 300)
    api.tick(env, 0.3)
    local base = foe:GetFrameLevel()
    T.eq(other:GetAlpha(), 1, "no target: nothing fades")
    target(env)
    -- the engine: alpha 1 for the target's plate, 178/255 for the rest
    other:SetAlpha(178 / 255)
    api.tick(env, 0.3)
    T.eq(foe:GetAlpha(), 1)
    T.ok(foe:GetFrameLevel() > other:GetFrameLevel(), "the target's plate draws on top")
    T.near(other:GetAlpha(), 0.6, 1e-6, "others fade")
    env.ClassicPlus_Manager:SetSetting("Plates", "fadeOthers", false)
    api.tick(env, 0.3)
    T.near(other:GetAlpha(), 178 / 255, 1e-6, "the engine's dim again")
    api.set_target(env, nil)
    other:SetAlpha(1)
    api.tick(env, 0.3)
    T.eq(foe:GetFrameLevel(), base, "no target: back to its level")
end)

T.test("Plates: in combat no plate fades; after the fight the others fade again", function()
    local env = visage()
    local foe = api.place_nameplate(env, api.add_nameplate(env, { name = "Defias Thug" }), 400, 300)
    local other = api.place_nameplate(env, api.add_nameplate(env, { name = "Kobold" }), 600, 300)
    api.tick(env, 0.3)
    local base = foe:GetFrameLevel()
    target(env)
    other:SetAlpha(178 / 255)          -- the engine dims the plates you are not targeting
    api.set_combat(env, true)
    api.tick(env, 0.3)
    T.eq(foe:GetAlpha(), 1)
    T.eq(other:GetAlpha(), 1, "in combat: full strength, no fade")
    T.ok(foe:GetFrameLevel() > other:GetFrameLevel(), "the target's plate still draws on top")
    api.set_combat(env, false)
    api.tick(env, 0.3)
    T.near(other:GetAlpha(), 0.6, 1e-6, "out of combat the others fade again")
    T.eq(foe:GetAlpha(), 1, "and the target stays bright")
    T.ok(foe:GetFrameLevel() > base, "on top")
end)

