T.test("Plates: placement off, or the addon off, gives the engine's stock placement back", function()
    local env = visage()
    local p = api.place_nameplate(env, api.add_nameplate(env, { name = "Boar" }), 400, 300)
    local q = api.place_nameplate(env, api.add_nameplate(env, { name = "Wolf" }), 410, 302)
    api.tick(env, 1)
    T.eq(hbY(p), 8)
    env.ClassicPlus_Manager:SetSetting("Plates", "liftPlates", false)
    api.tick(env, 0.3)
    local y, a, rel, b = hbY(p)
    T.eq(a .. " " .. b, "BOTTOMLEFT BOTTOMLEFT", "the engine's bar anchor"); T.eq(rel, p); T.eq(y, 4)
    T.eq(hbY(q), 4, "no stacking either: the engine's own solver handles it")
    local _, _, name = p:GetRegions()
    local na, nrel, nb = name:GetPoint(1)
    T.eq(na .. " " .. nb, "BOTTOM CENTER"); T.eq(nrel, p)
    T.eq(p:GetChildren():GetHeight(), 9, "stock bar height")
    env.ClassicPlus_Manager:SetSetting("Plates", "liftPlates", true)
    api.tick(env, 1)
    T.eq(hbY(p), 8, "and lifted again")
    env.ClassicPlus_Manager:SetSetting("Plates", "stacking", false)
    api.tick(env, 1)
    T.eq(hbY(q), 8, "stacking off: lifted but not pushed")
    env.WenillaCore:SetAddonEnabled("Plates", false)
    T.eq(select(2, hbY(p)), "BOTTOMLEFT", "addon off: stock anchors")
end)

