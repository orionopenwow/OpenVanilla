T.test("Talents: the planner follows the talent rules and shows what is left", function()
    local env = talents()
    env.__slash("/talents")
    local win = env.Talents_Planner
    T.shown(win)
    T.ok(api.screen_has(env, "Beast Mastery", win))
    T.ok(api.screen_has(env, "Remaining 51", win))
    local hawk, monkey = env.Talents_PlanBtn1_1, env.Talents_PlanBtn1_4
    api.click(monkey)
    T.ok(api.screen_has(env, "Needs 5 points in Beast Mastery first.", win), "tier 2 locked")
    for _ = 1, 6 do api.click(hawk) end
    T.ok(api.screen_has(env, "Already at its highest rank.", win))
    T.eq(api.visible(hawk.badge:GetText()), "5/5")
    api.click(monkey)
    T.eq(api.visible(monkey.badge:GetText()), "1/5", "tier 2 open now")
    T.ok(api.screen_has(env, "Remaining 45", win))
    T.ok(api.screen_has(env, "Planned 6", win))
    api.click(hawk, "RightButton")
    T.ok(api.screen_has(env, "needs the points in the tiers below it", win), "can't pull the floor out")
    api.click(monkey, "RightButton")
    api.click(hawk, "RightButton")
    T.eq(api.visible(hawk.badge:GetText()), "4/5")
    -- prerequisite: Bestial Wrath (7,2) needs Intimidation (5,2)
    api.enter(env.Talents_PlanBtn1_11)
    T.has(api.tooltip_text(env), "Needs 30 points in Beast Mastery first.")
end)

T.test("Talents: export, import, saved builds and the plan surviving a relog", function()
    local env = talents()
    env.__slash("/talents")
    local P = env.ClassicPlusTalents.Planner
    T.ok(P:Import("hunter/5500-5"), "import")
    T.eq(P:Encode(), "hunter/55-5")
    T.eq(api.visible(env.Talents_PlanBtn2_1.badge:GetText()), "5/5")
    T.no(P:Import("mage/5"), "another class")
    T.ok(api.screen_has(env, "That build is for a mage.", env.Talents_Planner))
    T.no(P:Import("hunter/0005"), "tier rules")
    T.ok(api.screen_has(env, "breaks the talent rules", env.Talents_Planner))
    T.no(P:Import("hunter/9"), "rank over max")
    T.no(P:Import("hunter/5x"), "junk")
    -- save through the buttons
    api.click_text(env, "Save", env.Talents_Planner)
    api.type(env.WenillaCore_PromptEdit, "Leveling")
    api.press_enter(env.WenillaCore_PromptEdit)
    api.click_text(env, "Clear", env.Talents_Planner)
    T.eq(P:Encode(), "hunter/")
    api.click_text(env, "Load", env.Talents_Planner)
    api.click_text(env, "Leveling", env.WenillaCore_Menu)
    T.eq(P:Encode(), "hunter/55-5", "loaded")
    api.click_text(env, "Export", env.Talents_Planner)
    T.eq(env.WenillaCore_PromptEdit:GetText(), "hunter/55-5")
    local again = T.relog(env)
    again.__slash("/talents")
    T.eq(again.ClassicPlusTalents.Planner:Encode(), "hunter/55-5", "the plan is remembered")
    T.eq(again.ClassicPlusTalents_DB.builds.HUNTER[1].name, "Leveling")
end)

