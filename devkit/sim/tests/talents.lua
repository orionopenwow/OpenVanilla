T.test("Talents: Reset asks, sends respec and reports RS ok / err", function()
    local env = talents()
    spend(env)
    api.connect(env)
    api.server_packet(env, "SP", "1,2;Raid;PvP")
    api.load_talent_ui(env)
    env.TalentFrame:Show()
    api.click_text(env, "Reset Talents", env.Talents_Strip)
    T.eq(env.__popups[1].which, "CLASSICPLUS_RESPEC")
    T.has(env.__popups[1].text, "Reset every talent in Raid?")
    api.on_server(env, "respec", function() api.server_packet(env, "RS", "ok") end)
    api.popup_click(env, "CLASSICPLUS_RESPEC", 1)
    T.eq(env.__wnl[#env.__wnl], "respec")
    api.pump(env)
    T.has(api.chat_text(env), "Your talents have been reset.")
    T.ok(api.screen_has(env, "Talents reset"), "toast")
    api.on_server(env, "respec", function() api.server_packet(env, "RS", "err,cooldown") end)
    env.__slash("/talents reset")
    api.popup_click(env, "CLASSICPLUS_RESPEC", 1)
    api.pump(env)
    T.has(api.chat_text(env), "Couldn't reset your talents: you reset not long ago.")
    api.on_server(env, "respec", nil)
    env.__slash("/talents reset")
    api.popup_click(env, "CLASSICPLUS_RESPEC", 1)
    api.tick(env, 7)
    T.has(api.chat_text(env), "The realm didn't answer")
end)

