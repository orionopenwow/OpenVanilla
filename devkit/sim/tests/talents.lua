T.test("Talents: after a reset, Learn Plan puts your old build back", function()
    local env = talents()
    spend(env)
    api.connect(env)
    api.server_packet(env, "SP", "1,1;Spec 1")
    api.on_server(env, "respec", function()
        for _, tab in ipairs(env.__talents.tabs) do for _, x in ipairs(tab.talents) do x.rank = 0 end end
        env.__talents.points = 51
        api.server_packet(env, "RS", "ok")
    end)
    env.__slash("/talents reset")
    api.popup_click(env, "CLASSICPLUS_RESPEC", 1)
    api.pump(env)
    env.__slash("/talents")
    local P = env.ClassicPlusTalents.Planner
    T.eq(P:Encode(), "hunter/52", "the build before the reset is the plan")
    T.ok(api.screen_has(env, "Planned 7", env.Talents_Planner))
    P:StartLearning()
    api.tick(env, 1, 0.05)
    T.eq(env.__talents.tabs[1].talents[1].rank, 5)
    T.eq(env.__talents.tabs[1].talents[2].rank, 2)
end)

