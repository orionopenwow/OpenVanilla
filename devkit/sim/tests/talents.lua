-- Talents: free reset (RS), two specs (SP) with names and a switch bar, the planner (plans per
-- spec, saved builds, codes, Learn Plan), the hunter pet gate (PG) and learned-spell toasts (LL).
local T, api = ...

local function talents(opts)
    opts = opts or {}
    opts.latency = false
    local env = T.addon("Talents", opts)
    return env
end

-- spend some real points: 5 in Improved Aspect of the Hawk, 2 in Endurance Training
local function spend(env)
    local tabs = env.__talents.tabs
    tabs[1].talents[1].rank = 5
    tabs[1].talents[2].rank = 2
    env.__talents.points = env.__talents.points - 7
end

T.test("Talents: an old realm gets no spec tabs and a reset button that explains", function()
    local env = talents()
    api.load_talent_ui(env)
    env.TalentFrame:Show()
    T.shown(env.Talents_Strip, "panel on the talent frame")
    T.hidden(env.Talents_SpecBox, "no spec tabs without SP")
    T.ok(api.screen_has(env, "need the realm update", env.Talents_Strip))
    api.click_text(env, "Reset Talents", env.Talents_Strip)
    T.eq(#env.__popups, 0, "no confirm when the realm can't do it")
    T.has(api.chat_text(env), "Free talent resets need the realm update")
    T.eq(#env.__wnl, 0, "nothing sent")
end)

