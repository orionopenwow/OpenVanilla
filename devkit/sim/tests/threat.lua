-- Threat (Vanguard): VG packets drive three bars and the pull warning.
local T, api = ...

local function bar(env, i) local b = env["Vanguard_Bar" .. i]; return b.left:GetText(), b.right:GetText(), b.bar:GetValue() end

T.test("Threat: VG body fills tank, you and the room until pull", function()
    local env = T.addon("Threat")
    api.server_packet(env, "VG", "Ragnaros;Brakkus,100,1;Ilyndra,95,0;Herald,80,0;S,3,80,110")
    T.shown(env.Vanguard_Frame)
    T.ok(api.screen_has(env, "Ragnaros", env.Vanguard_Frame), "target name")
    local l, r, v = bar(env, 1)
    T.eq(l, "Brakkus"); T.eq(r, "100.0%"); T.near(v, 100 / 110, 1e-9)
    l, r = bar(env, 2)
    T.eq(l, "You"); T.eq(r, "80.0%")
    l, r, v = bar(env, 3)
    T.eq(l, "Until pull"); T.eq(r, "30.0%"); T.near(v, 30 / 110, 1e-9)
    T.no(env.Vanguard.warned)
end)

T.test("Threat: pull warning glows and plays the raid warning once", function()
    local env = T.addon("Threat")
    api.server_packet(env, "VG", "Ragnaros;Brakkus,100,1;Herald,104,0;S,2,104,110")
    T.ok(env.Vanguard.warned, "104 >= 90% of 110")
    T.eq(env.__sounds[1], "Sound\\Interface\\RaidWarning.wav")
    api.server_packet(env, "VG", "Ragnaros;Brakkus,100,1;Herald,106,0;S,2,106,110")
    T.eq(#env.__sounds, 1, "the sound plays once per warning")
    api.server_packet(env, "VG", "Ragnaros;Brakkus,100,1;Herald,50,0;S,2,50,110")
    T.no(env.Vanguard.warned)
    env.ClassicPlus_Manager:SetSetting("Threat", "soundAlert", false)
    api.server_packet(env, "VG", "Ragnaros;Brakkus,100,1;Herald,120,0;S,2,120,130")
    T.ok(env.Vanguard.warned)
    T.eq(#env.__sounds, 1, "soundAlert off")
end)

T.test("Threat: when you hold aggro the runner-up is shown", function()
    local env = T.addon("Threat")
    api.server_packet(env, "VG", "Hogger;Herald,100,1;Brakkus,80,0;S,1,100,110")
    local l, r = bar(env, 1)
    T.eq(l, "Herald")
    l, r = bar(env, 2)
    T.eq(l, "Brakkus"); T.eq(r, "80.0%")
    l, r = bar(env, 3)
    T.eq(l, "You have aggro"); T.eq(r, "0.0%")
    api.server_packet(env, "VG", "Hogger;Herald,100,1;S,1,100,110")
    T.hidden(env.Vanguard_Bar2, "nobody else on the table")
end)

T.test("Threat: '-' and stale data hide the window; /threat mutes it", function()
    local env = T.addon("Threat")
    api.server_packet(env, "VG", "Ragnaros;Brakkus,100,1;S,2,10,110")
    T.shown(env.Vanguard_Frame)
    api.server_packet(env, "VG", "-")
    T.hidden(env.Vanguard_Frame)
    api.server_packet(env, "VG", "Ragnaros;Brakkus,100,1;S,2,10,110")
    api.tick(env, 7)
    T.hidden(env.Vanguard_Frame, "no update for 6 s")
    env.__slash("/threat")
    T.has(api.chat_text(env), "Threat window hidden.")
    api.server_packet(env, "VG", "Ragnaros;Brakkus,100,1;S,2,10,110")
    T.hidden(env.Vanguard_Frame, "muted by /threat")
    env.__slash("/vanguard")
    api.server_packet(env, "VG", "Ragnaros;Brakkus,100,1;S,2,10,110")
    T.shown(env.Vanguard_Frame)
    api.server_packet(env, "VG", "Ragnaros;S,2,10,110")
    T.hidden(env.Vanguard_Frame, "an empty table hides it")
end)

T.test("Threat: showDelta setting and the close button", function()
    local env = T.addon("Threat")
    env.ClassicPlus_Manager:SetSetting("Threat", "showDelta", false)
    api.server_packet(env, "VG", "Ragnaros;Brakkus,100,1;S,2,10,110")
    T.hidden(env.Vanguard_Bar3)
    T.eq(env.Vanguard_Frame:GetHeight(), 87)
    api.click(env.Vanguard_Frame.closeButton)
    T.hidden(env.Vanguard_Frame)
    T.ok(env.Vanguard.userClosed)
end)
