-- Vendor (Scrapper): grey selling and repairs at merchants, with exact summaries.
local T, api = ...

local BAGS = { [0] = { size = 16, items = { { 7073, 3 }, { 2589, 20 }, { 7074, 1 } } } }

local function scrapper(opts)
    opts = opts or {}
    opts.bags = opts.bags or BAGS
    opts.money = opts.money or 100000
    return T.addon("Vendor", opts)
end

T.test("Vendor: opening a merchant repairs and sells the greys", function()
    local env = scrapper()
    api.open_merchant(env, { items = {}, repair = true, repairCost = 1234 })
    T.shown(env.Scrapper_Button)
    T.eq(api.bag_slot(env, 0, 1), nil, "grey sold")
    T.ok(api.bag_slot(env, 0, 2), "white kept")
    api.tick(env, 0.1)                      -- the server's coinage update arrives
    T.eq(env.GetMoney(), 100000 - 1234 + 3 * 6 + 4)
    api.tick(env, 1.6)
    T.has(api.chat_text(env), "Vendor: sold 2 grey items for 22c and repaired your gear for 12s 34c.")
    T.ok(api.find_text(env, "Scrap", env.Scrapper_Button), "button label")
    T.no(api.screen_has(env, "2", env.Scrapper_Button), "count cleared after the sale")
end)

T.test("Vendor: the sale summary is exact when Scrapper also repaired", function()
        local env = scrapper()
        api.open_merchant(env, { items = {}, repair = true, repairCost = 1234 })
        api.tick(env, 2)
        T.has(api.chat_text(env), "Vendor: sold 2 grey items for 22c and repaired your gear for 12s 34c.")
        local n = 0
        for _, l in ipairs(api.chat_lines(env)) do if string.find(l, "Vendor:", 1, true) then n = n + 1 end end
        T.eq(n, 1, "one summary line per visit")
    end)

T.test("Vendor: the Scrap button and its tooltip when auto-sell is off", function()
    local env = scrapper()
    env.ClassicPlus_Manager:SetSetting("Vendor", "autoSell", false)
    env.ClassicPlus_Manager:SetSetting("Vendor", "autoRepair", false)
    api.open_merchant(env, { items = {}, repair = true, repairCost = 500 })
    T.eq(env.GetMoney(), 100000, "nothing happens on open")
    T.ok(api.screen_has(env, "2", env.Scrapper_Button), "grey count on the button")
    api.enter(env.Scrapper_Button)
    local tip = api.tooltip_text(env)
    T.has(tip, "Sell 2 grey items and repair your gear.")
    T.has(tip, "Repair  =  5s 0c")
    env.__merchant.repairCost = 0            -- (repaired elsewhere: only the sale is measured)
    api.click(env.Scrapper_Button)
    api.tick(env, 1.6)
    T.eq(env.GetMoney(), 100000 + 22)
    T.has(api.chat_text(env), "Vendor: sold 2 grey items for 22c.")
end)

T.test("Vendor: with telemetry the sale is one server command", function()
    local env = scrapper()
    api.connect(env, "1", "Quests,Threat,Prices,Plates,Vendor")
    api.on_server(env, "sc", function(args) T.eq(args, "sell"); api.server_packet(env, "SC", "2,22") end)
    api.open_merchant(env, { items = {} })
    api.pump(env)
    T.eq(env.__wnl[2], "sc sell")
    T.ok(api.bag_slot(env, 0, 1), "the client did not sell item by item")
    T.has(api.chat_text(env), "Vendor: sold 2 grey items for 22c.")
    T.eq(env.Scrapper.pending, nil)
end)

T.test("Vendor: a realm whose greeting lacks Vendor (today's) gets the sale item by item", function()
    local env = scrapper()
    api.connect(env, "1", "Quests,Threat,Prices,Plates")
    api.open_merchant(env, { items = {} })
    api.tick(env, 1.6)
    for _, l in ipairs(env.__wnl) do T.no(l == "sc sell", "no server sale") end
    T.eq(env.GetMoney(), 100000 + 22, "sold by the client")
    T.has(api.chat_text(env), "Vendor: sold 2 grey items for 22c.")
end)

T.test("Vendor: with telemetry the summary includes the repair too", function()
    local env = scrapper()
    api.connect(env, "1", "Quests,Threat,Prices,Plates,Vendor")
    api.on_server(env, "sc", function() api.server_packet(env, "SC", "2,22") end)
    api.open_merchant(env, { items = {}, repair = true, repairCost = 100 })
    api.tick(env, 0.2)
    T.has(api.chat_text(env), "Vendor: sold 2 grey items for 22c and repaired your gear for 1s 0c.")
end)

T.test("Vendor: no repair when it cannot be afforded; summaries can be muted", function()
    local env = scrapper({ money = 1000 })
    env.ClassicPlus_Manager:SetSetting("Vendor", "printSummary", false)
    api.open_merchant(env, { items = {}, repair = true, repairCost = 5000 })
    api.tick(env, 2)
    T.eq(env.GetMoney(), 1000 + 22, "sold, not repaired")
    T.lacks(api.chat_text(env), "Vendor:")
end)

T.test("Vendor: auto sell and auto repair are on by default; a repair you cannot afford says so", function()
    local env = scrapper({ money = 1000 })
    T.eq(env.WenillaCore:Setting("Vendor", "autoSell"), true)
    T.eq(env.WenillaCore:Setting("Vendor", "autoRepair"), true)
    T.eq(env.WenillaCore:Setting("Vendor", "printSummary"), true)
    api.open_merchant(env, { items = {}, repair = true, repairCost = 5000 })
    api.tick(env, 2)
    T.has(api.chat_text(env), "Vendor: repairs cost 50s 0c; you have 10s 0c.")
    T.has(api.chat_text(env), "Vendor: sold 2 grey items for 22c.")
end)

T.test("Vendor: repair only (no greys) still gets its line; locked items are left alone", function()
    local env = scrapper({ bags = { [0] = { size = 16, items = { { 2589, 20 } } } } })
    api.open_merchant(env, { items = {}, repair = true, repairCost = 250 })
    api.tick(env, 0.2)
    T.has(api.chat_text(env), "Vendor: repaired your gear for 2s 50c.")
    api.close_merchant(env)
    local env2 = scrapper({ name = "Ann" })
    env2.__bags[0].items[1].locked = true
    api.open_merchant(env2, { items = {} })
    api.tick(env2, 2)
    T.ok(api.bag_slot(env2, 0, 1), "the locked grey stays")
    T.has(api.chat_text(env2), "Vendor: sold 1 grey item for 4c.")
end)

T.test("Vendor: /scrap away from a merchant counts greys; disabled hides the button", function()
    local env = scrapper()
    env.__slash("/scrap")
    T.has(api.chat_text(env), "Vendor: 2 grey items in your bags. Open a merchant to sell.")
    env.WenillaCore:SetAddonEnabled("Vendor", false)
    api.open_merchant(env, { items = {}, repair = true, repairCost = 100 })
    api.tick(env, 0.5)
    T.hidden(env.Scrapper_Button)
    T.eq(env.GetMoney(), 100000, "a disabled Scrapper does nothing")
end)
