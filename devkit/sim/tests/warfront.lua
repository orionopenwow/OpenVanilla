    T.shown(env.WarfrontFrame, "the PvP tab opens Warfront")
    T.hidden(env.Dungeons_Frame, "in the same place")
end)

T.test("Warfront: malformed lines never raise", function()
    local env = wf()
    connect(env, "1")
    for _, tag in ipairs({ "WF", "WK", "WS", "WE", "WP", "WB", "WH", "WL", "WV", "WR", "WN", "WQ", "WC", "WG" }) do
        for _, body in ipairs({ "", "-", ",,,", ";;;", "ok", "err", "x;y;z", "1,2,3,4,5,6,7,8,9", "15;a,b;19364" }) do
            api.server_packet(env, tag, body)
        end
    end
    env.__slash("/wf")
    for _, k in ipairs({ "kits", "gear", "shop", "sets", "arena" }) do env.__slash("/wf " .. k) end
end)
