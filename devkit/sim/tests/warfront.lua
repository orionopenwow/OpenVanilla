T.test("Warfront: Equip kit sends the kit key and shows the realm's answer", function()
    local env = wf()
    connect(env, "1,0,0,0,0")
    T.ok(not env.WarfrontFrame or not env.WarfrontFrame:IsVisible(), "not the first login: stays closed")
    env.__slash("/wf")
    T.shown(env.WarfrontFrame)
    api.click_text(env, "Equip kit", env.WarfrontFrame)
    api.pump(env)
    T.has(sent(env), "wf kit warrior-arms-a")
    api.server_packet(env, "WK", "err,combat")
    T.ok(api.screen_has(env, "Not in combat.", env.WarfrontFrame))
    api.server_packet(env, "WK", "ok,warrior-arms-a,16,9")
    T.ok(api.screen_has(env, "Kit equipped: 16 items, 9 enchants.", env.WarfrontFrame))
end)

T.test("Warfront: the gear picker lists a slot's items, greys locked tiers and equips one", function()
    local env = wf()
    api.add_item(env, 19364, { name = "Ashkandi, Greatsword of the Brotherhood" })
    api.add_item(env, 21134, { name = "Dark Edge of Insanity" })
    connect(env, "1,0,10,1500,0")
    env.__slash("/wf gear")
    T.shown(env.WarfrontFrame)
    api.click_text(env, "Main hand", env.WarfrontFrame)
    api.pump(env)
    T.has(sent(env), "wf pool 15")
    api.server_packet(env, "WP", "15;19364,0;21134,2")
    local t = texts(env)
    T.has(t, "Ashkandi, Greatsword of the Brotherhood")
    T.has(t, "Dark Edge of Insanity  (tier 2)")
    local before = table.getn(env.__wnl)
    api.click_text(env, "Dark Edge of Insanity", env.WarfrontFrame)
    api.pump(env)
    T.eq(table.getn(env.__wnl), before, "a locked item isn't asked for")
    T.ok(api.screen_has(env, "Locked", env.WarfrontFrame))
    api.click_text(env, "Ashkandi, Greatsword of the Brotherhood", env.WarfrontFrame)
    api.pump(env)
    T.has(sent(env), "wf slot 15 19364")
    api.server_packet(env, "WS", "ok,15,19364")
    T.ok(api.screen_has(env, "Ashkandi, Greatsword of the Brotherhood equipped.", env.WarfrontFrame))
    -- the main hand's enchants come from the data file
    api.click_text(env, "Enchant Weapon - Crusader", env.WarfrontFrame)
    api.pump(env)
    T.has(sent(env), "wf ench 15 20034")
    api.server_packet(env, "WE", "err,slot")
    T.ok(api.screen_has(env, "That doesn't go in that slot.", env.WarfrontFrame))
end)

