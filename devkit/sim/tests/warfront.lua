T.test("Warfront: Group Finder gets a Player vs. Player tab only on Warfront", function()
    local env = T.suite({ latency = false, class = "WARRIOR" })
    api.connect(env)
    api.tick(env, 1)
    api.server_packet(env, "WF", "0")
    api.click(env.OVGroupFinderMicroButton)
    T.shown(env.Dungeons_Frame, "Group Finder opens Dungeons & Raids")
    T.no(string.find(table.concat(api.visible_texts(env, env.OVHubTabs_finder), " "), "Player vs. Player", 1, true),
