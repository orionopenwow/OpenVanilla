-- Warfront: the realm's window (kits, gear picker, enchants, shop, shared sets) and the arena tab.
-- The server side is OpenVanilla/Warfront.cpp and WarfrontArena.cpp; the lines here follow their headers.
local T, api = ...

local function wf(opts)
    opts = opts or {}
    opts.latency = false
    opts.class = opts.class or "WARRIOR"
    opts.faction = opts.faction or "Alliance"
    return T.addon("Warfront", opts)
end

-- greet, and let the addon ask "wf hi"
local function connect(env, hello)
    api.connect(env)
    api.tick(env, 1)
    if hello then api.server_packet(env, "WF", hello) end
end

local function sent(env) return table.concat(env.__wnl, " | ") end

local function texts(env) return table.concat(api.visible_texts(env, env.WarfrontFrame), " | ") end

T.test("Warfront: asks the realm once connected; a realm without Warfront keeps it hidden", function()
    local env = wf()
    T.no(string.find(sent(env), "wf hi", 1, true), "nothing before the greeting")
    connect(env, "0")
    T.has(sent(env), "wf hi")
    env.__slash("/wf")
    T.has(api.chat_text(env), "works on the Warfront realm only")
    T.ok(not env.WarfrontFrame or not env.WarfrontFrame:IsVisible(), "no window")
    api.tick(env, 2)
    local n = 0
    for _, l in ipairs(env.__wnl) do if l == "wf hi" then n = n + 1 end end
    T.eq(n, 1, "asked once")
end)

T.test("Warfront: the first login opens the kits for the character's class and faction", function()
    local env = wf()
    connect(env, "1,0,0,0,1")
