T.test("Warfront: sharing the gear on now, the realm's list, votes and reports", function()
    local env = wf()
    api.add_item(env, 16478, { name = "Field Marshal's Plate Helm" })
    api.add_item(env, 19364, { name = "Ashkandi, Greatsword of the Brotherhood" })
    connect(env, "1,0,0,0,0")
    env.__slash("/wf sets")
    api.pump(env)
    T.has(sent(env), "wf sets", "the list is asked for on opening")
    -- nothing worn yet
    api.click_text(env, "Share my gear", env.WarfrontFrame)
    T.ok(api.screen_has(env, "Give the set a name.", env.WarfrontFrame))
    env.__inventory[1] = 16478
    env.__inventory[16] = 19364
    local page = env.Warfront.pages.sets
    api.type(page.name, "Big <Hits>")
    api.click_text(env, "Share my gear", env.WarfrontFrame)
    api.pump(env)
    T.has(sent(env), "wf share PvP~Big Hits~0:16478,15:19364")
    api.server_packet(env, "WH", "ok,7")
    T.ok(api.screen_has(env, "Shared.", env.WarfrontFrame))
    api.server_packet(env, "WL", "7,2,Herald,PvP,Big Hits,0:16478/15:19364;9,0,Berra,Arms,Slow,15:19364")
    local t = texts(env)
    T.has(t, "Big Hits")
    T.has(t, "by Herald, 2 votes")
    api.click_text(env, "Vote", env.WarfrontFrame)
    api.pump(env)
    T.has(sent(env), "wf vote 7")
    api.server_packet(env, "WV", "ok,7,3")
    T.has(texts(env), "3 votes")
    api.click_text(env, "Apply", env.WarfrontFrame)
    api.tick(env, 1)                                    -- the .wnl flood guard sends 4 a second
    T.has(sent(env), "wf apply 7")
    api.server_packet(env, "WK", "ok,set7,2,0")
    T.ok(api.screen_has(env, "2 items on, 0 skipped", env.WarfrontFrame))
    api.server_packet(env, "WR", "err,self")
    T.ok(api.screen_has(env, "own set", env.WarfrontFrame))
    api.server_packet(env, "WL", "-")
    T.ok(api.screen_has(env, "No shared sets for your class yet", env.WarfrontFrame))
end)

T.test("Warfront: arena queue, pop, preparation, fight and the result", function()
    local env = wf()
    connect(env, "1,0,0,0,0")
    env.__slash("/arena")
    T.shown(env.WarfrontFrame)
    api.pump(env)
    T.has(sent(env), "wf q rating")
    api.server_packet(env, "WQ", "r,1500,1500,1500")
    T.has(texts(env), "2v2 1500")
    api.click_text(env, "2v2 Rated", env.WarfrontFrame)
    api.pump(env)
    T.has(sent(env), "wf q join r2")
    api.server_packet(env, "WQ", "q,r2,0,3")
    T.has(texts(env), "Queued: 2v2 Rated")
    api.server_packet(env, "WQ", "pop,r2,4,1")
    T.has(table.concat(api.visible_texts(env), " | "), "Arena match found")
    T.has(texts(env), "In a 2v2 Rated match")
    api.server_packet(env, "WQ", "prep,60")
    T.ok(api.screen_has(env, "The gates open in 60 seconds", env.WarfrontFrame))
    api.tick(env, 2)
    T.has(texts(env), "starts in")
    api.server_packet(env, "WQ", "go")
    T.ok(api.screen_has(env, "Fight!", env.WarfrontFrame))
    api.server_packet(env, "WQ", "end,1,16,1516")
    T.ok(api.screen_has(env, "Victory.  +16 rating (1516)", env.WarfrontFrame))
    T.has(texts(env), "Not queued.")
    api.server_packet(env, "WQ", "pop,s2,5,0")
    api.server_packet(env, "WQ", "err,battleground")
    T.ok(api.screen_has(env, "Leave the battleground", env.WarfrontFrame))
    T.has(texts(env), "Not queued.", "a match the realm dropped us from is cleared")
    api.server_packet(env, "WQ", "err,locked,600")
    T.ok(api.screen_has(env, "queue opens again in 10 min", env.WarfrontFrame))
    api.server_packet(env, "WQ", "top,r2;Herald,1650;Berra,1600")
    T.has(texts(env), "1. Herald  1650")
    env.__slash("/arena leave")
    api.pump(env)
    T.has(sent(env), "wf q leave")
end)

