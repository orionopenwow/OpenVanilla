/// A WDBC file: records of 32-bit words and a string block.
#[derive(Debug, Clone)]
pub struct Dbc {
    pub fields: usize,
    pub records: Vec<Vec<u32>>,
    pub strings: Vec<u8>,
}

impl Dbc {
    pub fn parse(b: &[u8]) -> Result<Dbc> {
        if b.len() < 20 || &b[..4] != b"WDBC" {
            bail!("not a WDBC file");
        }
        let u = |o: usize| u32::from_le_bytes(b[o..o + 4].try_into().unwrap()) as usize;
        let (n, fields, size, ssize) = (u(4), u(8), u(12), u(16));
        if size != fields * 4 {
            bail!("record size {size} isn't {fields} 32-bit fields");
        }
        if b.len() < 20 + n * size + ssize {
            bail!("file is cut short");
        }
        let records = (0..n).map(|i| (0..fields).map(|f| u(20 + i * size + f * 4) as u32).collect()).collect();
        Ok(Dbc { fields, records, strings: b[20 + n * size..20 + n * size + ssize].to_vec() })
    }

    pub fn string(&self, off: u32) -> String {
        let o = off as usize;
        if o >= self.strings.len() {
            return String::new();
        }
        let end = self.strings[o..].iter().position(|&c| c == 0).map(|e| o + e).unwrap_or(self.strings.len());
        String::from_utf8_lossy(&self.strings[o..end]).to_string()
    }

    pub fn find(&self, id: u32) -> Option<usize> {
        self.records.iter().position(|r| r[0] == id)
    }

    pub fn write(&self) -> Vec<u8> {
        let mut out = Vec::with_capacity(20 + self.records.len() * self.fields * 4 + self.strings.len());
        out.extend_from_slice(b"WDBC");
        for v in [self.records.len(), self.fields, self.fields * 4, self.strings.len()] {
            out.extend_from_slice(&(v as u32).to_le_bytes());
        }
        for r in &self.records {
            for w in r {
                out.extend_from_slice(&w.to_le_bytes());
            }
        }
        out.extend_from_slice(&self.strings);
        out
    }
}

/// Which words of a record are string offsets.
fn string_slots(s: &DbcTable) -> Vec<bool> {
    let mut v = Vec::with_capacity(s.record_fields);
    for f in &s.fields {
        for _ in 0..f.count {
            match f.kind.as_str() {
                "string" => v.push(true),
                "locstring" => {
                    v.extend(std::iter::repeat(true).take(8));
                    v.push(false);
                }
                _ => v.push(false),
            }
        }
    }
    v
}

fn dbc_path(t: &str) -> String {
    format!("DBFilesClient\\{t}.dbc")
}

pub fn read_stock(g: &GameData, t: &str) -> Result<Dbc> {
    let s = &dbc_schema()[t];
    let d = Dbc::parse(&g.read(&dbc_path(t))?).with_context(|| format!("{t}.dbc"))?;
    if d.fields != s.record_fields {
        bail!("your {t}.dbc has {} fields, Forge expects {} (is this the right game client?)", d.fields, s.record_fields);
    }
    Ok(d)
}

/// Apply one row to a record: `words` (a donor/stock record or zeros) and its strings by slot.
fn apply_row(s: &DbcTable, r: &toml::Table, words: &mut [u32], strs: &mut BTreeMap<usize, String>) {
    for (k, v) in r {
        if is_meta(k) {
            continue;
        }
        let Some((at, f)) = s.field(k) else { continue };
        let items: Vec<&Value> = match v {
            Value::Array(a) => a.iter().collect(),
            x => vec![x],
        };
        let step = if f.kind == "locstring" { 9 } else { 1 };
        for (n, item) in items.iter().enumerate().take(f.count) {
            let w = at + n * step;
            match f.kind.as_str() {
                "string" | "locstring" => {
                    strs.insert(w, item.as_str().unwrap_or("").to_string());
                }
                "float" => words[w] = (item.as_float().or(item.as_integer().map(|i| i as f64)).unwrap_or(0.0) as f32).to_bits(),
                _ => words[w] = item.as_integer().or(item.as_bool().map(i64::from)).unwrap_or(0) as i32 as u32,
            }
        }
    }
}

/// Merge the pack's rows into a stock DBC (dev builds): clones, overrides and new records, with a
/// fresh, de-duplicated string block.
pub fn merge(t: &str, stock: &Dbc, rows: &[toml::Table]) -> Result<Dbc> {
    let s = &dbc_schema()[t];
    let slots = string_slots(s);
    let mut recs: Vec<(Vec<u32>, BTreeMap<usize, String>)> = stock
        .records
        .iter()
        .map(|r| (r.clone(), slots.iter().enumerate().filter(|(_, x)| **x).map(|(i, _)| (i, stock.string(r[i]))).collect()))
        .collect();
    let mut index: HashMap<u32, usize> = recs.iter().enumerate().map(|(i, r)| (r.0[0], i)).collect();
    for r in rows {
        let id = r.get("ID").and_then(Value::as_integer).context("a row has no ID")? as u32;
        let (base, base_strs) = if let Some(&i) = index.get(&id) {
            recs[i].clone()
        } else if let Some(donor) = r.get("clone").and_then(Value::as_integer) {
            recs[*index.get(&(donor as u32)).with_context(|| format!("{t}: clone = {donor} isn't there"))?].clone()
        } else {
            (vec![0; s.record_fields], BTreeMap::new())
        };
        let (mut words, mut strs) = (base, base_strs);
        words[0] = id;
        apply_row(s, r, &mut words, &mut strs);
        match index.get(&id) {
            Some(&i) => recs[i] = (words, strs),
            None => {
                index.insert(id, recs.len());
                recs.push((words, strs));
            }
        }
    }
    recs.sort_by_key(|r| r.0[0]);
    let mut strings = vec![0u8];
    let mut interned: HashMap<String, u32> = HashMap::new();
    let records = recs
        .into_iter()
        .map(|(mut w, strs)| {
            for (i, sv) in strs {
                w[i] = if sv.is_empty() {
                    0
                } else {
                    *interned.entry(sv.clone()).or_insert_with(|| {
                        let off = strings.len() as u32;
                        strings.extend_from_slice(sv.as_bytes());
                        strings.push(0);
                        off
                    })
                };
            }
            w
        })
        .collect();
    Ok(Dbc { fields: s.record_fields, records, strings })
}

/// Stock records whose ID is `q` or whose text contains it (case-insensitive): the Data screen's
/// donor search ("Fireball", "Horse", 133). Each hit: ID and a label from the table's text fields.
pub fn search_stock(t: &str, d: &Dbc, q: &str, limit: usize) -> Vec<J> {
    let s = &dbc_schema()[t];
    let slots = string_slots(s);
    let ql = q.trim().to_ascii_lowercase();
    let id = ql.parse::<u32>().ok();
    let mut out = vec![];
    for r in &d.records {
        let texts: Vec<String> = slots.iter().enumerate().filter(|(_, x)| **x).map(|(i, _)| d.string(r[i])).filter(|x| !x.is_empty()).collect();
        let hit = id == Some(r[0]) || (!ql.is_empty() && id.is_none() && texts.iter().any(|x| x.to_ascii_lowercase().contains(&ql)));
        if hit {
            out.push(json!({"ID": r[0], "label": texts.first().cloned().unwrap_or_default(), "more": texts.get(1).cloned().unwrap_or_default()}));
            if out.len() >= limit {
                break;
            }
        }
    }
    out
}

/// What a record looks like as JSON (the Data screen's "stock row" view).
pub fn record_json(t: &str, d: &Dbc, i: usize) -> J {
    let s = &dbc_schema()[t];
    let r = &d.records[i];
    let mut o = serde_json::Map::new();
    let mut at = 0;
    for f in &s.fields {
        let step = if f.kind == "locstring" { 9 } else { 1 };
        let one = |w: usize| -> J {
            match f.kind.as_str() {
                "string" | "locstring" => json!(d.string(r[w])),
                "float" => json!(f32::from_bits(r[w])),
                "uint" => json!(r[w]),
                _ => json!(r[w] as i32),
            }
        };
        let v = if f.count == 1 { one(at) } else { J::Array((0..f.count).map(|n| one(at + n * step)).collect()) };
        o.insert(f.name.clone(), v);
        at += f.count * step;
    }
    J::Object(o)
}

