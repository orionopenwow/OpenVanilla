// ---------------------------------------------------------------- schemas

#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct Column {
    pub name: String,
    /// int | float | string
    #[serde(rename = "type")]
    pub kind: String,
    pub sql: String,
    pub default: Option<J>,
    pub null: bool,
    #[serde(default)]
    pub comment: String,
}

#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct WorldTable {
    pub columns: Vec<Column>,
    pub key: Vec<String>,
}

#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct DbcField {
    pub name: String,
    /// int | uint | float | string | locstring
    #[serde(rename = "type")]
    pub kind: String,
    pub count: usize,
    #[serde(default)]
    pub id: bool,
}

#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct DbcTable {
    pub fields: Vec<DbcField>,
    /// 32-bit words in one record (a 1.12 locstring is 8 strings + a flags word).
    pub record_fields: usize,
}

pub fn world_schema() -> &'static BTreeMap<String, WorldTable> {
    static S: OnceLock<BTreeMap<String, WorldTable>> = OnceLock::new();
    S.get_or_init(|| serde_json::from_str(include_str!("../schemas/world.json")).expect("world.json"))
}

pub fn dbc_schema() -> &'static BTreeMap<String, DbcTable> {
    static S: OnceLock<BTreeMap<String, DbcTable>> = OnceLock::new();
    S.get_or_init(|| serde_json::from_str(include_str!("../schemas/dbc.json")).expect("dbc.json"))
}

impl WorldTable {
    pub fn column(&self, name: &str) -> Option<&Column> {
        self.columns.iter().find(|c| c.name.eq_ignore_ascii_case(name))
    }
}

impl DbcTable {
    pub fn field(&self, name: &str) -> Option<(usize, &DbcField)> {
        let mut at = 0;
        for f in &self.fields {
            if f.name.eq_ignore_ascii_case(name) {
                return Some((at, f));
            }
            at += f.count * if f.kind == "locstring" { 9 } else { 1 };
        }
        None
    }
}

fn table_name<'a, T>(map: &'a BTreeMap<String, T>, name: &str) -> Option<&'a str> {
    map.keys().find(|k| k.eq_ignore_ascii_case(name)).map(String::as_str)
}

/// The closest column name, for "did you mean".
fn near<'a>(names: impl Iterator<Item = &'a str>, want: &str) -> Option<&'a str> {
    let w = want.to_ascii_lowercase();
    names
        .map(|n| (lev(&n.to_ascii_lowercase(), &w), n))
        .filter(|(d, _)| *d <= 3)
        .min_by_key(|(d, _)| *d)
        .map(|(_, n)| n)
}

fn lev(a: &str, b: &str) -> usize {
    let b: Vec<char> = b.chars().collect();
    let mut row: Vec<usize> = (0..=b.len()).collect();
    for (i, ca) in a.chars().enumerate() {
        let mut prev = row[0];
        row[0] = i + 1;
        for j in 0..b.len() {
            let cur = row[j + 1];
            row[j + 1] = (prev + (ca != b[j]) as usize).min(row[j] + 1).min(row[j + 1] + 1);
            prev = cur;
        }
    }
    row[b.len()]
}

// ---------------------------------------------------------------- the project's rows

/// One table's rows from a project file.
#[derive(Debug, Clone, Default, Serialize)]
pub struct Rows {
    /// The project file, relative (data/world/x.toml).
    pub file: String,
    pub rows: Vec<toml::Table>,
}

#[derive(Debug, Clone, Default, Serialize)]
pub struct Data {
    /// Table name (as the schema spells it) -> rows.
    pub world: BTreeMap<String, Rows>,
    pub dbc: BTreeMap<String, Rows>,
    /// Files that didn't parse or name an unknown table.
    #[serde(skip)]
    pub problems: Vec<Finding>,
}

const META: &[&str] = &["override", "clone", "comment"];

fn is_meta(k: &str) -> bool {
    META.contains(&k)
}

fn is_override(r: &toml::Table) -> bool {
    r.get("override").and_then(Value::as_bool).unwrap_or(false)
}

fn data_dir(p: &Project, kind: &str) -> PathBuf {
    p.root.join("data").join(kind)
}

pub fn load(p: &Project) -> Data {
    let mut d = Data::default();
    for (kind, names) in [("world", world_schema().keys().cloned().collect::<Vec<_>>()), ("dbc", dbc_schema().keys().cloned().collect())] {
        let dir = data_dir(p, kind);
        let Ok(rd) = std::fs::read_dir(&dir) else { continue };
        let mut files: Vec<PathBuf> = rd.filter_map(|e| e.ok()).map(|e| e.path()).filter(|f| f.extension().is_some_and(|e| e == "toml")).collect();
        files.sort();
        for f in files {
            let rel = format!("data/{kind}/{}", f.file_name().unwrap().to_string_lossy());
            let stem = f.file_stem().unwrap().to_string_lossy().to_string();
            let Some(name) = names.iter().find(|n| n.eq_ignore_ascii_case(&stem)) else {
                let hint = near(names.iter().map(String::as_str), &stem).map(|n| format!(" (did you mean {n}?)")).unwrap_or_default();
                d.problems.push(Finding::error("data.table", &rel, format!("Forge doesn't edit a {kind} table called {stem}{hint}. It edits: {}", names.join(", "))));
                continue;
            };
            let parsed = std::fs::read_to_string(&f).map_err(anyhow::Error::from).and_then(|t| Ok(t.parse::<toml::Table>()?));
            match parsed {
                Err(e) => d.problems.push(Finding::error("data.toml", &rel, format!("isn't valid TOML: {e}"))),
                Ok(t) => {
                    let rows = match t.get("row") {
                        None => vec![],
                        Some(Value::Array(a)) => a.iter().filter_map(|v| v.as_table().cloned()).collect(),
                        Some(_) => {
                            d.problems.push(Finding::error("data.toml", &rel, "rows go in [[row]] tables"));
                            vec![]
                        }
                    };
                    let target = if kind == "world" { &mut d.world } else { &mut d.dbc };
                    target.insert(name.clone(), Rows { file: rel, rows });
                }
            }
        }
    }
    d
}

/// Write one table's rows back (the Data screen saves through this).
pub fn save_rows(p: &Project, kind: &str, table: &str, rows: &[toml::Table]) -> Result<PathBuf> {
    let name = match kind {
        "world" => table_name(world_schema(), table),
        "dbc" => table_name(dbc_schema(), table),
        _ => bail!("kind is world or dbc"),
    }
    .with_context(|| format!("unknown {kind} table {table}"))?
    .to_string();
    let dir = data_dir(p, kind);
    std::fs::create_dir_all(&dir)?;
    let f = dir.join(format!("{name}.toml"));
    if rows.is_empty() {
        let _ = std::fs::remove_file(&f);
        return Ok(f);
    }
    let mut out = format!("# {name}: rows this pack adds or (override = true) changes. Edited by Forge's Data screen.\n");
    for r in rows {
        out.push_str("\n[[row]]\n");
        // the meta keys first, then the columns in the table's own order
        let order = column_order(kind, &name);
        let mut keys: Vec<&String> = r.keys().collect();
        keys.sort_by_key(|k| (if is_meta(k) { 0 } else { 1 }, order.iter().position(|o| o.eq_ignore_ascii_case(k)).unwrap_or(usize::MAX), k.to_string()));
        for k in keys {
            let mut one = toml::Table::new();
            one.insert(k.clone(), r[k].clone());
            out.push_str(&toml::to_string(&one)?);
        }
    }
    std::fs::write(&f, out)?;
    Ok(f)
}

fn column_order(kind: &str, table: &str) -> Vec<String> {
    if kind == "world" {
        world_schema()[table].columns.iter().map(|c| c.name.clone()).collect()
    } else {
        dbc_schema()[table].fields.iter().map(|f| f.name.clone()).collect()
    }
}

