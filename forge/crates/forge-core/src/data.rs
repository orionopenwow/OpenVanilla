//! Game data a pack adds or changes: rows in the realm's world tables (creatures, items, quests,
//! loot, gossip, vendors ...) and records in the client's DBC tables (displays, models, spells,
//! spell icons). Plan §4.3.
//!
//! A pack never ships whole tables, only its own rows, as TOML a person can read and diff:
//!
//! ```text
//! data/world/creature_template.toml     [[row]] Entry = 1100001, Name = "Emberwing Drake", ...
//! data/world/creature_loot_template.toml
//! data/dbc/CreatureDisplayInfo.toml     [[row]] ID = 40001, clone = 2410, ModelID = 5001, ...
//! ```
//!
//! * A row with a key in the pack's own ID range is a **new** row. Columns it leaves out take the
//!   table's defaults (world) or the `clone` donor's values / zero (DBC).
//! * A row with `override = true` changes a **stock** row in place. The install SQL backs the old
//!   row up first, so `rollback.sql` puts it back exactly.
//!
//! The build turns this into `server/sql/install.sql` + `rollback.sql` (explicit column lists,
//! re-runnable) and `data/dbc/<Table>.json` (the delta the realm merges into its DBCs). A **dev**
//! build also merges the DBC deltas into the creator's own DBCs, so the local client sees them
//! (those merged files are never published: they're the game's files).
//!
//! The table layouts come from `schemas/` (generated by `forge/schemas/gen_schemas.py` from
//! CMaNGOS Classic's `mangos.sql` and WoWDBDefs' 1.12.1 definitions).

