/// Against a real 1.12.1 client's DBCs: `FORGE_REAL_DBC=<dir with spell.dbc ...> cargo test real_dbc -- --ignored`
#[cfg(test)]
mod real {
    use super::*;

    fn load_real(t: &str) -> Option<Dbc> {
        let dir = std::env::var("FORGE_REAL_DBC").ok()?;
        let b = std::fs::read(Path::new(&dir).join(format!("{}.dbc", t.to_ascii_lowercase()))).ok()?;
        Some(Dbc::parse(&b).unwrap())
    }

    #[test]
    #[ignore]
    fn real_dbc_layouts_and_lossless_merge() {
        for t in dbc_schema().keys() {
            let Some(d) = load_real(t) else { panic!("set FORGE_REAL_DBC") };
            assert_eq!(d.fields, dbc_schema()[t].record_fields, "{t} field count");
            let m = merge(t, &d, &[]).unwrap();
            assert_eq!(m.records.len(), d.records.len());
            let by_id: HashMap<u32, usize> = d.records.iter().enumerate().map(|(i, r)| (r[0], i)).collect();
            for i in 0..m.records.len() {
                let j = by_id[&m.records[i][0]];
                assert_eq!(record_json(t, &m, i), record_json(t, &d, j), "{t} record {} survives a merge", m.records[i][0]);
            }
            println!("{t}: {} records, strings {} -> {}", d.records.len(), d.strings.len(), m.strings.len());
        }
        let spell = load_real("Spell").unwrap();
        let fireball = record_json("Spell", &spell, spell.find(133).unwrap());
        println!("Spell 133: {} / {}", fireball["Name_lang"], fireball["SpellIconID"]);
        let rows: Vec<toml::Table> = vec![toml::from_str("ID = 60001\nclone = 133\nName_lang = \"Emberbolt\"").unwrap()];
        let m = merge("Spell", &spell, &rows).unwrap();
        let e = record_json("Spell", &m, m.find(60001).unwrap());
        assert_eq!(e["Name_lang"], "Emberbolt");
        assert_eq!(e["SpellIconID"], fireball["SpellIconID"]);
        assert_eq!(e["Description_lang"], fireball["Description_lang"]);
    }
}
