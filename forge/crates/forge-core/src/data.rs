/// Take a spawn (creature or gameobject) out by guid.
pub fn remove_spawn(p: &Project, table: &str, guid: i64) -> Result<()> {
    if !["creature", "gameobject"].contains(&table) {
        bail!("spawns are creature or gameobject");
    }
    let d = load(p);
    let rows: Vec<toml::Table> = d.world.get(table).map(|r| r.rows.iter().filter(|x| x.get("guid").and_then(Value::as_integer) != Some(guid)).cloned().collect()).unwrap_or_default();
    save_rows(p, "world", table, &rows)?;
    Ok(())
}

