/// The table whose ID range governs a key column (`creature_loot_template.entry` is any loot id,
/// so only primary tables are range-checked).
fn ranged_key(table: &str) -> Option<(&'static str, &'static str)> {
    Some(match table {
        "creature_template" => ("Entry", "creature_template"),
        "item_template" => ("entry", "item_template"),
        "quest_template" => ("entry", "quest_template"),
        "gameobject_template" => ("entry", "gameobject_template"),
        "creature" => ("guid", "creature"),
        "gameobject" => ("guid", "gameobject"),
        "npc_text" => ("ID", "npc_text"),
        "gossip_menu" => ("entry", "gossip_menu"),
        "CreatureDisplayInfo" => ("ID", "CreatureDisplayInfo"),
        "CreatureModelData" => ("ID", "CreatureModelData"),
        "ItemDisplayInfo" => ("ID", "ItemDisplayInfo"),
        "Spell" => ("ID", "Spell"),
        "SpellIcon" => ("ID", "SpellIcon"),
        "Map" => ("ID", "Map"),
        "AreaTable" => ("ID", "AreaTable"),
        "AreaTrigger" => ("ID", "AreaTrigger"),
        "LoadingScreens" => ("ID", "LoadingScreens"),
        "Light" => ("ID", "Light"),
        "LightParams" => ("ID", "LightParams"),
        "game_tele" => ("id", "game_tele"),
        "areatrigger_teleport" => ("id", "AreaTrigger"),
        "instance_template" => ("map", "Map"),
        _ => return None,
    })
}

fn int_bounds(sql: &str) -> (i64, i64) {
    let uns = sql.contains("unsigned");
    let bits = if sql.starts_with("tinyint") { 8 } else if sql.starts_with("smallint") { 16 } else if sql.starts_with("mediumint") { 24 } else if sql.starts_with("bigint") { 63 } else { 32 };
    if bits == 63 {
        return (if uns { 0 } else { i64::MIN }, i64::MAX);
    }
    if uns { (0, (1i64 << bits) - 1) } else { (-(1i64 << (bits - 1)), (1i64 << (bits - 1)) - 1) }
}

fn type_ok(kind: &str, v: &Value) -> bool {
    match kind {
        "int" | "uint" => matches!(v, Value::Integer(_) | Value::Boolean(_)),
        "float" => matches!(v, Value::Integer(_) | Value::Float(_)),
        _ => matches!(v, Value::String(_)),
    }
}

pub fn check(p: &Project, game: Option<&GameData>) -> Vec<Finding> {
    let d = load(p);
    let mut out = d.problems.clone();
    let lock = IdLock::load(&p.root).unwrap_or_default();
    for (t, rows) in &d.world {
        let s = &world_schema()[t];
        let mut seen: HashMap<String, usize> = HashMap::new();
        for (i, r) in rows.rows.iter().enumerate() {
            let at = format!("{} row {}", rows.file, i + 1);
            for (k, v) in r {
                if is_meta(k) {
                    continue;
                }
                match s.column(k) {
                    None => {
                        let hint = near(s.columns.iter().map(|c| c.name.as_str()), k).map(|n| format!(" (did you mean {n}?)")).unwrap_or_default();
                        out.push(Finding::error("data.column", &at, format!("{t} has no column {k}{hint}")));
                    }
                    Some(c) if !type_ok(&c.kind, v) => out.push(Finding::error("data.type", &at, format!("{k} is a {} column, not {}", c.kind, v.type_str()))),
                    Some(c) if c.kind == "int" => {
                        let n = v.as_integer().unwrap_or(v.as_bool().map(i64::from).unwrap_or(0));
                        let (lo, hi) = int_bounds(&c.sql);
                        if n < lo || n > hi {
                            out.push(Finding::error("data.range", &at, format!("{k} = {n} doesn't fit {} ({lo}..{hi})", c.sql)));
                        }
                    }
                    Some(c) if c.kind == "string" => {
                        if let Some(len) = c.sql.strip_prefix("varchar(").and_then(|x| x.trim_end_matches(')').parse::<usize>().ok()) {
                            if v.as_str().unwrap().chars().count() > len {
                                out.push(Finding::error("data.length", &at, format!("{k} is longer than {len} characters")));
                            }
                        }
                    }
                    _ => {}
                }
            }
            if s.key.is_empty() {
                continue;
            }
            let missing: Vec<&String> = s.key.iter().filter(|k| !r.keys().any(|x| x.eq_ignore_ascii_case(k))).collect();
            if !missing.is_empty() {
                out.push(Finding::error("data.key", &at, format!("a {t} row needs {}", missing.iter().map(|x| x.as_str()).collect::<Vec<_>>().join(" and "))));
                continue;
            }
            let key = key_values(s, r).join(",");
            if let Some(prev) = seen.insert(key.clone(), i + 1) {
                out.push(Finding::error("data.duplicate", &at, format!("{t} ({key}) is already row {prev}")));
            }
            range_check(t, r, &lock, &at, &mut out);
            if let Some(c) = r.get("clone") {
                if s.key.len() != 1 {
                    out.push(Finding::error("data.clone", &at, format!("clone works on tables with one key column; {t} has {}", s.key.len())));
                } else if c.as_integer().is_none() {
                    out.push(Finding::error("data.clone", &at, "clone is the stock row's key (a number)"));
                } else if is_override(r) {
                    out.push(Finding::error("data.clone", &at, "a row is either a clone (a new row) or an override (a changed stock row), not both"));
                }
            }
        }
    }
    for (t, rows) in &d.dbc {
        let s = &dbc_schema()[t];
        let stock = game.and_then(|g| read_stock(g, t).ok());
        let mut seen: HashMap<i64, usize> = HashMap::new();
        for (i, r) in rows.rows.iter().enumerate() {
            let at = format!("{} row {}", rows.file, i + 1);
            for (k, v) in r {
                if is_meta(k) {
                    continue;
                }
                match s.field(k) {
                    None => {
                        let hint = near(s.fields.iter().map(|f| f.name.as_str()), k).map(|n| format!(" (did you mean {n}?)")).unwrap_or_default();
                        out.push(Finding::error("data.column", &at, format!("{t} has no field {k}{hint}")));
                    }
                    Some((_, f)) => {
                        let items: Vec<&Value> = match v {
                            Value::Array(a) => a.iter().collect(),
                            x => vec![x],
                        };
                        if matches!(v, Value::Array(_)) != (f.count > 1) {
                            out.push(Finding::error("data.type", &at, if f.count > 1 { format!("{k} is a list of {}: write {k} = [ ... ]", f.count) } else { format!("{k} is one value, not a list") }));
                        } else if items.len() > f.count {
                            out.push(Finding::error("data.type", &at, format!("{k} holds {} values, not {}", f.count, items.len())));
                        } else if let Some(bad) = items.iter().find(|x| !type_ok(if f.kind == "locstring" { "string" } else { &f.kind }, x)) {
                            out.push(Finding::error("data.type", &at, format!("{k} is {}, not {}", f.kind, bad.type_str())));
                        }
                    }
                }
            }
            let Some(id) = r.iter().find(|(k, _)| k.eq_ignore_ascii_case("ID")).and_then(|(_, v)| v.as_integer()) else {
                out.push(Finding::error("data.key", &at, format!("a {t} row needs an ID")));
                continue;
            };
            if let Some(prev) = seen.insert(id, i + 1) {
                out.push(Finding::error("data.duplicate", &at, format!("{t} {id} is already row {prev}")));
            }
            range_check(t, r, &lock, &at, &mut out);
            if let Some(st) = &stock {
                let exists = st.find(id as u32).is_some();
                if is_override(r) && !exists {
                    out.push(Finding::error("data.override", &at, format!("{t} {id} isn't in your game, so there's nothing to override")));
                }
                if !is_override(r) && exists {
                    out.push(Finding::error("data.clash", &at, format!("{t} {id} is a stock record: set override = true to change it")));
                }
                if let Some(donor) = r.get("clone").and_then(Value::as_integer) {
                    if st.find(donor as u32).is_none() && !rows.rows.iter().any(|o| o.get("ID").and_then(Value::as_integer) == Some(donor)) {
                        out.push(Finding::error("data.clone", &at, format!("clone = {donor}: no {t} {donor} in your game or this pack")));
                    }
                }
            }
        }
    }
    if !d.dbc.is_empty() && game.is_none() {
        out.push(Finding::info("data.nogame", "data/dbc", "Forge can't compare the DBC rows with the game's until you set your game folder."));
    }
    out
}

fn range_check(t: &str, r: &toml::Table, lock: &IdLock, at: &str, out: &mut Vec<Finding>) {
    let Some((col, idt)) = ranged_key(t) else { return };
    let Some(id) = r.iter().find(|(k, _)| k.eq_ignore_ascii_case(col)).and_then(|(_, v)| v.as_integer()) else { return };
    if is_override(r) {
        if lock.owns(idt, id as u32) {
            out.push(Finding::warning("data.override", at, format!("{col} {id} is the pack's own ID: override is for changing stock rows")));
        } else {
            out.push(Finding::info("data.override", at, format!("changes stock {t} {id}; rollback.sql puts it back")));
        }
    } else if !lock.owns(idt, id as u32) {
        let range = lock.tables.get(idt).map(|r| format!("{}..{}", r.start, r.end)).unwrap_or_else(|| "none yet: take one on the Project page".into());
        out.push(Finding::error("data.id", at, format!("{col} {id} is outside the pack's {idt} range ({range}); a stock row needs override = true")));
    }
}

fn key_values(s: &WorldTable, r: &toml::Table) -> Vec<String> {
    s.key.iter().map(|k| r.iter().find(|(x, _)| x.eq_ignore_ascii_case(k)).map(|(_, v)| sql_value(v)).unwrap_or_default()).collect()
}

// ---------------------------------------------------------------- SQL

fn sql_value(v: &Value) -> String {
    match v {
        Value::Integer(n) => n.to_string(),
        Value::Float(f) => {
            let s = f.to_string();
            if s.contains('.') || s.contains('e') { s } else { format!("{s}.0") }
        }
        Value::Boolean(b) => (*b as i32).to_string(),
        Value::String(s) => format!("'{}'", s.replace('\\', "\\\\").replace('\'', "''").replace('\n', "\\n").replace('\r', "\\r")),
        other => format!("'{}'", other.to_string().replace('\'', "''")),
    }
}

fn backup_table(pack: &str, t: &str) -> String {
    format!("forge_backup_{}_{}", pack.replace('-', "_"), t)
}

/// `(install.sql, rollback.sql)` for the world rows.
pub fn sql(p: &Project, d: &Data) -> (String, String) {
    let pack = &p.manifest.pack.id;
    let head = format!(
        "-- {} {} ({}): generated by Vanilla Forge. Re-runnable; undo with rollback.sql.\n",
        p.manifest.pack.name, p.manifest.pack.version, pack
    );
    let mut ins = head.clone();
    let mut rb = head.replace("Re-runnable; undo with rollback.sql.", "Puts back what install.sql changed.");
    let mut backups = vec![];
    for (t, rows) in &d.world {
        if rows.rows.is_empty() {
            continue;
        }
        let s = &world_schema()[t];
        ins.push_str(&format!("\n-- {t} ({})\n", rows.file));
        rb.push_str(&format!("\n-- {t}\n"));
        let key_where = |r: &toml::Table| -> String {
            if s.key.is_empty() {
                return "0".into();
            }
            s.key.iter().zip(key_values(s, r)).map(|(k, v)| format!("`{k}` = {v}")).collect::<Vec<_>>().join(" AND ")
        };
        let cols = |r: &toml::Table| -> Vec<(String, String)> {
            // in the table's own column order, so the SQL reads like the table
            s.columns
                .iter()
                .filter_map(|c| r.iter().find(|(k, _)| !is_meta(k) && k.eq_ignore_ascii_case(&c.name)).map(|(_, v)| (c.name.clone(), sql_value(v))))
                .collect()
        };
        for r in &rows.rows {
            let w = key_where(r);
            let c = cols(r);
            if is_override(r) {
                let b = backup_table(pack, t);
                if !backups.contains(&(b.clone(), t.clone())) {
                    ins.push_str(&format!("CREATE TABLE IF NOT EXISTS `{b}` LIKE `{t}`;\n"));
                    backups.push((b.clone(), t.clone()));
                }
                // keep the first backup: re-running install never overwrites the true stock row
                ins.push_str(&format!("INSERT IGNORE INTO `{b}` SELECT * FROM `{t}` WHERE {w};\n"));
                let set: Vec<String> = c.iter().filter(|(k, _)| !s.key.contains(k)).map(|(k, v)| format!("`{k}` = {v}")).collect();
                if !set.is_empty() {
                    ins.push_str(&format!("UPDATE `{t}` SET {} WHERE {w};\n", set.join(", ")));
                }
                // only when the backup holds the row (a rollback that runs before any install, or
                // twice, changes nothing)
                rb.push_str(&format!(
                    "CREATE TABLE IF NOT EXISTS `{b}` LIKE `{t}`;\nDELETE FROM `{t}` WHERE {w} AND EXISTS (SELECT 1 FROM `{b}` WHERE {w});\nINSERT IGNORE INTO `{t}` SELECT * FROM `{b}` WHERE {w};\n"
                ));
            } else if let (Some(donor), [key]) = (r.get("clone").and_then(Value::as_integer), s.key.as_slice()) {
                // a copy of a stock row with the given columns changed: every other column (faction,
                // flags, AI ...) is the donor's
                let id = key_values(s, r).remove(0);
                let mut set = vec![format!("`{key}` = {id}")];
                set.extend(c.iter().filter(|(k, _)| k != key).map(|(k, v)| format!("`{k}` = {v}")));
                ins.push_str(&format!(
                    "DELETE FROM `{t}` WHERE {w};\nDROP TEMPORARY TABLE IF EXISTS `forge_tmp`;\n\
                     CREATE TEMPORARY TABLE `forge_tmp` SELECT * FROM `{t}` WHERE `{key}` = {donor};\n\
                     UPDATE `forge_tmp` SET {};\nINSERT INTO `{t}` SELECT * FROM `forge_tmp`;\nDROP TEMPORARY TABLE `forge_tmp`;\n",
                    set.join(", ")
                ));
                rb.push_str(&format!("DELETE FROM `{t}` WHERE {w};\n"));
            } else {
                // NOT NULL columns with no default must be given: fill them with the type's zero
                let mut c = c;
                for col in &s.columns {
                    if !col.null && col.default.is_none() && !c.iter().any(|(k, _)| k == &col.name) {
                        c.push((col.name.clone(), if col.kind == "string" { "''".into() } else { "0".into() }));
                    }
                }
                if !s.key.is_empty() {
                    ins.push_str(&format!("DELETE FROM `{t}` WHERE {w};\n"));
                }
                ins.push_str(&format!(
                    "INSERT INTO `{t}` ({}) VALUES ({});\n",
                    c.iter().map(|(k, _)| format!("`{k}`")).collect::<Vec<_>>().join(", "),
                    c.iter().map(|(_, v)| v.as_str()).collect::<Vec<_>>().join(", ")
                ));
                if s.key.is_empty() {
                    rb.push_str(&format!(
                        "DELETE FROM `{t}` WHERE {};\n",
                        c.iter().map(|(k, v)| format!("`{k}` = {v}")).collect::<Vec<_>>().join(" AND ")
                    ));
                } else {
                    rb.push_str(&format!("DELETE FROM `{t}` WHERE {w};\n"));
                }
            }
        }
    }
    if let Some(rows) = d.dbc.get("Spell").filter(|r| !r.rows.is_empty()) {
        spell_sql(pack, &rows.rows, &rows.file, &mut ins, &mut rb, &mut backups);
    }
    if !backups.is_empty() {
        rb.push('\n');
        for (b, _) in &backups {
            rb.push_str(&format!("DROP TABLE IF EXISTS `{b}`;\n"));
        }
    }
    (ins, rb)
}

/// Spell.dbc field -> CMaNGOS `spell_template` column: the server reads spells from the database,
/// not from Spell.dbc (`schemas/spell_template_map.py`; checked against all 22,357 1.12.1 spells).
pub fn spell_columns() -> &'static BTreeMap<String, String> {
    static S: OnceLock<BTreeMap<String, String>> = OnceLock::new();
    S.get_or_init(|| serde_json::from_str(include_str!("../schemas/spell_template.json")).expect("spell_template.json"))
}

/// One Spell row's values as `spell_template` assignments (`col = value` SQL fragments).
fn spell_sets(r: &toml::Table) -> Vec<(String, String)> {
    let s = &dbc_schema()["Spell"];
    let map = spell_columns();
    let mut out = vec![];
    for (k, v) in r {
        if is_meta(k) {
            continue;
        }
        let Some((_, f)) = s.field(k) else { continue };
        let items: Vec<&Value> = match v {
            Value::Array(a) => a.iter().collect(),
            x => vec![x],
        };
        for (n, item) in items.iter().enumerate().take(f.count) {
            let key = if f.count == 1 { f.name.clone() } else { format!("{}[{n}]", f.name) };
            let Some(col) = map.get(&key) else { continue };
            let val = sql_value(item);
            match col.split_once(':') {
                Some((c, "lo")) => out.push((c.to_string(), format!("((`{c}` & 0xFFFFFFFF00000000) | ({val} & 0xFFFFFFFF))"))),
                Some((c, _)) => out.push((c.to_string(), format!("((`{c}` & 0xFFFFFFFF) | (({val} & 0xFFFFFFFF) << 32))"))),
                None => out.push((col.clone(), val)),
            }
        }
    }
    out
}

fn spell_sql(pack: &str, rows: &[toml::Table], file: &str, ins: &mut String, rb: &mut String, backups: &mut Vec<(String, String)>) {
    let t = "spell_template";
    ins.push_str(&format!("\n-- {t}: the server's copy of the Spell rows ({file})\n"));
    rb.push_str(&format!("\n-- {t}\n"));
    for r in rows {
        let Some(id) = r.get("ID").and_then(Value::as_integer) else { continue };
        let w = format!("`Id` = {id}");
        let sets: Vec<String> = spell_sets(r).into_iter().filter(|(c, _)| c != "Id").map(|(c, v)| format!("`{c}` = {v}")).collect();
        if is_override(r) {
            let b = backup_table(pack, t);
            if !backups.iter().any(|(x, _)| x == &b) {
                ins.push_str(&format!("CREATE TABLE IF NOT EXISTS `{b}` LIKE `{t}`;\n"));
                backups.push((b.clone(), t.to_string()));
            }
            ins.push_str(&format!("INSERT IGNORE INTO `{b}` SELECT * FROM `{t}` WHERE {w};\n"));
            if !sets.is_empty() {
                ins.push_str(&format!("UPDATE `{t}` SET {} WHERE {w};\n", sets.join(", ")));
            }
            rb.push_str(&format!(
                "CREATE TABLE IF NOT EXISTS `{b}` LIKE `{t}`;\nDELETE FROM `{t}` WHERE {w} AND EXISTS (SELECT 1 FROM `{b}` WHERE {w});\nINSERT IGNORE INTO `{t}` SELECT * FROM `{b}` WHERE {w};\n"
            ));
        } else {
            let donor = r.get("clone").and_then(Value::as_integer);
            ins.push_str(&format!("DELETE FROM `{t}` WHERE {w};\n"));
            match donor {
                Some(dn) => {
                    let mut all = vec![format!("`Id` = {id}")];
                    all.extend(sets);
                    ins.push_str(&format!(
                        "DROP TEMPORARY TABLE IF EXISTS `forge_tmp`;\nCREATE TEMPORARY TABLE `forge_tmp` SELECT * FROM `{t}` WHERE `Id` = {dn};\nUPDATE `forge_tmp` SET {};\nINSERT INTO `{t}` SELECT * FROM `forge_tmp`;\nDROP TEMPORARY TABLE `forge_tmp`;\n",
                        all.join(", ")
                    ));
                }
                None => {
                    // a spell from nothing: the row with its defaults, then the given columns
                    ins.push_str(&format!("INSERT INTO `{t}` (`Id`) VALUES ({id});\n"));
                    if !sets.is_empty() {
                        ins.push_str(&format!("UPDATE `{t}` SET {} WHERE {w};\n", sets.join(", ")));
                    }
                }
            }
            rb.push_str(&format!("DELETE FROM `{t}` WHERE {w};\n"));
        }
    }
}

