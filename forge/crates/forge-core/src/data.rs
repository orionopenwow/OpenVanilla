    let mut r = toml::Table::new();
    let f = |x: f64| Value::Float((x * 1000.0).round() / 1000.0);
    r.insert("guid".into(), (guid as i64).into());
    r.insert("id".into(), entry.into());
    r.insert("map".into(), (pos.map as i64).into());
    r.insert("position_x".into(), f(pos.x));
    r.insert("position_y".into(), f(pos.y));
    r.insert("position_z".into(), f(pos.z));
    r.insert("orientation".into(), f(pos.o));
    // the turn as a quaternion about the up axis
    r.insert("rotation2".into(), Value::Float(((pos.o / 2.0).sin() * 1e6).round() / 1e6));
    r.insert("rotation3".into(), Value::Float(((pos.o / 2.0).cos() * 1e6).round() / 1e6));
