/// JSON rows from the UI -> TOML tables (numbers stay integers where they are whole and the column
/// is an integer one).
pub fn rows_from_json(kind: &str, table: &str, v: &J) -> Result<Vec<toml::Table>> {
    let arr = v.as_array().context("rows must be a list")?;
    let float_col = |k: &str| -> bool {
        if kind == "world" {
            table_name(world_schema(), table).and_then(|t| world_schema()[t].column(k)).is_some_and(|c| c.kind == "float")
        } else {
            table_name(dbc_schema(), table).and_then(|t| dbc_schema()[t].field(k)).is_some_and(|(_, f)| f.kind == "float")
        }
    };
    fn conv(x: &J, float: bool) -> Option<Value> {
        Some(match x {
            J::Null => return None,
            J::Bool(b) => Value::Boolean(*b),
            J::Number(n) => {
                if float {
                    Value::Float(n.as_f64()?)
                } else if let Some(i) = n.as_i64() {
                    Value::Integer(i)
                } else {
                    Value::Float(n.as_f64()?)
                }
            }
            J::String(s) => Value::String(s.clone()),
            J::Array(a) => Value::Array(a.iter().filter_map(|y| conv(y, float)).collect()),
            J::Object(_) => return None,
        })
    }
    let mut out = vec![];
    for r in arr {
        let obj = r.as_object().context("each row is an object")?;
        let mut t = toml::Table::new();
        for (k, x) in obj {
            if let Some(v) = conv(x, float_col(k)) {
                t.insert(k.clone(), v);
            }
        }
        out.push(t);
    }
    Ok(out)
}

