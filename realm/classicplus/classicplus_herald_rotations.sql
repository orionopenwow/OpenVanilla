-- (co +custom::herald_mage_20, the other bands off). Applied by hetzner/openvanilla_realm_up.sh; safe to
-- run twice. Undo: DELETE FROM classiccharacters.ai_playerbot_custom_strategy WHERE owner = 0 AND name LIKE 'herald\_%\_%';
-- Warriors from 20 have no Overpower line: the class strategies hold Berserker Stance from 30, and Overpower
-- needs Battle Stance, so the line would make him switch stances back and forth.
-- herald_rotations.sql
-- Solo-leveling combat priorities for Herald (cmangos playerbots self-bot, WoW 1.12.1).
-- One custom strategy per class and level band: herald_<class>_<1|20|40>  (bands 1-19, 20-39, 40-60).
-- Rows are owner 0 (global); a row set with owner = <bot guid> would override it for that character.
-- Line syntax (playerbot/strategy/CustomStrategy.cpp): trigger>action!relevance[,action!relevance...]
--   no spaces around '>' ',' '!'; every trigger/action name was checked against the creators[...] maps
--   (see names_check.txt). Lines run ON TOP of the class strategies; relevances are kept < 90 (ACTION_EMERGENCY)
--   and heals stay in the 50-70 heal tier.
-- Enable in combat:   .bot cmd <name> co +custom::herald_mage_20     (remove the old band with co -custom::herald_mage_1)
-- After editing rows, toggle the strategy off/on (or reset the bot AI) so the cached lines are reloaded.
-- Priority logic is from public Classic leveling guides (see ROTATIONS.md). No wowsims rotation/APL files were
-- present locally (/home/claude/dl/sod only holds apl.proto), so no wowsims content was used.

