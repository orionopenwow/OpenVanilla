import unittest
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "launcher"))
import ed25519  # noqa: E402
import forge_verify as V  # noqa: E402

SECRET = bytes(range(32))

# what forge-core/data.rs writes (an insert, a clone, an override and their rollback)
GOOD_SQL = """-- Ember Pack 0.1.0 (ember-pack): generated by Open Vanilla Forge.
DELETE FROM `creature_template` WHERE `Entry` = 1426000;
INSERT INTO `creature_template` (`Entry`, `Name`) VALUES (1426000, 'Ember; DROP TABLE x ''drake''');
DELETE FROM `creature_template` WHERE `Entry` = 1426001;
DROP TEMPORARY TABLE IF EXISTS `forge_tmp`;
CREATE TEMPORARY TABLE `forge_tmp` SELECT * FROM `creature_template` WHERE `Entry` = 308;
UPDATE `forge_tmp` SET `Entry` = 1426001, `Scale` = 1.0;
INSERT INTO `creature_template` SELECT * FROM `forge_tmp`;
DROP TEMPORARY TABLE `forge_tmp`;
CREATE TABLE IF NOT EXISTS `forge_backup_ember_pack_creature_template` LIKE `creature_template`;
INSERT IGNORE INTO `forge_backup_ember_pack_creature_template` SELECT * FROM `creature_template` WHERE `Entry` = 448;
UPDATE `creature_template` SET `Name` = 'Hogger' WHERE `Entry` = 448;
DELETE FROM `creature_template` WHERE `Entry` = 448 AND EXISTS (SELECT 1 FROM `forge_backup_ember_pack_creature_template` WHERE `Entry` = 448);
INSERT IGNORE INTO `creature_template` SELECT * FROM `forge_backup_ember_pack_creature_template` WHERE `Entry` = 448;
DROP TABLE IF EXISTS `forge_backup_ember_pack_creature_template`;
DELETE FROM `spell_template` WHERE `Id` = 70000;
UPDATE `forge_tmp` SET `Id` = 70000, `SpellFamilyFlags` = ((`SpellFamilyFlags` & 0xFFFFFFFF00000000) | (4 & 0xFFFFFFFF));
"""


def make_pack(path, files, secret=SECRET, tamper=None):
    lines = sorted(f"{n} {hashlib.sha256(b).hexdigest()}" for n, b in files.items())
    digest = hashlib.sha256("\n".join(lines).encode()).hexdigest()
    sig = {"format": "openvanilla-forge-pack/1", "pack": "ember-pack", "version": "0.1.0", "build_hash": "0" * 64,
           "contents": digest, "public_key": ed25519.public_key(secret).hex(),
           "signature": ed25519.sign(secret, V.SIGNED_PREFIX + digest.encode()).hex()}
    with zipfile.ZipFile(path, "w") as z:
        for n, b in files.items():
            z.writestr(n, tamper(n, b) if tamper else b)
        z.writestr("SIGNATURE.json", json.dumps(sig))


class ForgeVerify(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.files = {"forge.toml": b"[pack]\n", "server/sql/install.sql": GOOD_SQL.encode(),
                      "manifest.json": json.dumps([{"path": "Creature\\EmberPack\\Tail\\Tail.m2"}]).encode()}

    def path(self, n="p.ovpack"):
        return os.path.join(self.tmp, n)

    def test_a_good_pack_passes(self):
        make_pack(self.path(), self.files)
        sig, names, n = V.verify(self.path(), key=ed25519.public_key(SECRET).hex())
        self.assertEqual(sig["pack"], "ember-pack")
        self.assertEqual(n, 1)

    def test_tampering_and_the_wrong_key_are_refused(self):
        make_pack(self.path(), self.files, tamper=lambda n, b: b + b"\n" if n == "forge.toml" else b)
        with self.assertRaisesRegex(V.Refused, "changed after"):
            V.verify(self.path())
        make_pack(self.path("k.ovpack"), self.files)
        with self.assertRaisesRegex(V.Refused, "different key"):
            V.verify(self.path("k.ovpack"), key="00" * 32)

    def test_sql_outside_what_forge_writes_is_refused(self):
        allowed = V.world_tables()
        V.check_sql(GOOD_SQL, allowed)
        for bad, why in [
            ("DELETE FROM `account` WHERE 1;", "account"),
            ("UPDATE `characters`.`characters` SET `money` = 1;", "another database"),
            ("INSERT INTO `creature_template` SELECT * FROM `account`;", "account"),
            ("DROP TABLE `creature_template`;", "doesn't write"),
            ("SELECT * FROM `creature_template` INTO OUTFILE '/tmp/x';", "may not"),
            ("UPDATE `creature_template` SET `Name` = SLEEP(5) WHERE `Entry` = 1;", "may not"),
            ("GRANT ALL ON *.* TO 'x';", "may not"),
        ]:
            with self.assertRaisesRegex(V.Refused, why, msg=bad):
                V.check_sql(bad, allowed)

    def test_client_files_stay_in_game_folders(self):
        self.files["manifest.json"] = json.dumps([{"path": "WTF\\Config.wtf"}]).encode()
        make_pack(self.path(), self.files)
        with self.assertRaisesRegex(V.Refused, "WTF"):
            V.verify(self.path())


if __name__ == "__main__":
    unittest.main()
