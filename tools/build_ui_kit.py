def main():
    os.makedirs(DST, exist_ok=True)
    meta = {}
    for fn in sorted(os.listdir(SRC)):
        if not fn.endswith(".png"):
            continue
        name = fn[:-4]
        img = Image.open(os.path.join(SRC, fn)).convert("RGBA")
        if name == "stone-tile":  # already 1x and tileable: no 2x master to downsample from
            img.save(os.path.join(DST, "stone-tile.webp"), "WEBP", quality=88, method=6)
            img.save(os.path.join(DST, "stone-tile@2x.webp"), "WEBP", quality=88, method=6)
            meta[name] = {"w": img.width, "h": img.height, "slice": None, "tile": True}
            continue
        w, h = export(name, img)
        meta[name] = {"w": w, "h": h, "slice": slice_for(name)}
    with open(os.path.join(DST, "kit.json"), "w", encoding="utf-8") as f:
        json.dump({"version": 1, "pieces": meta}, f, indent=1)
    with open(os.path.join(DST, "kit.css"), "w", encoding="utf-8", newline="\n") as f:
        f.write(build_css(meta))
    total = sum(os.path.getsize(os.path.join(DST, x)) for x in os.listdir(DST))
    print(f"kit: {len(meta)} pieces, {total / 1024:.0f} KB in {os.path.normpath(DST)}")


if __name__ == "__main__":
    main()
