"""Turn the 4x art masters in art/ui-kit/ into the web kit used by Server Studio (and anything else).

    py -3 tools/gen_ui_art.py && py -3 tools/build_ui_kit.py

Writes www/studio/kit/:
  <piece>.webp / <piece>@2x.webp   1x and 2x exports of every master
  kit.json                         size and 9-slice insets per piece (1x CSS px)
  kit.css                          one class per component and state, built only from these images

A 9-slice inset is [top, right, bottom, left]: that many pixels at each edge stay fixed (the
corners and their ornaments); the rest stretches. Change an inset here, never in kit.css.
"""
import json
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "art", "ui-kit")
DST = os.path.join(HERE, "..", "www", "studio", "kit")
S = 4

# piece prefix -> 9-slice inset at 1x (None = fixed-size image)
SLICES = {
    "plate-": [14, 14, 14, 14],
    "tab-": [14, 14, 3, 14],
    "frame-window": [26, 26, 26, 26],
    "card-": [14, 14, 14, 14],
    "field-": [8, 8, 8, 8],
    "plaque": [12, 26, 12, 26],
    "bar-": [6, 6, 6, 6],
}


def slice_for(name):
    for prefix, inset in SLICES.items():
        if name.startswith(prefix):
            return inset
    return None


def export(name, img):
    w1, h1 = img.width // S, img.height // S
    img.resize((w1 * 2, h1 * 2), Image.LANCZOS).save(os.path.join(DST, f"{name}@2x.webp"), "WEBP", lossless=True, method=6)
    img.resize((w1, h1), Image.LANCZOS).save(os.path.join(DST, f"{name}.webp"), "WEBP", lossless=True, method=6)
    return w1, h1


def url(name):
    return f'image-set(url("{name}.webp") 1x, url("{name}@2x.webp") 2x)'


def border(name, inset, fill=True):
    t, r, b, l = inset
    return (f"border-style: solid; border-width: {t}px {r}px {b}px {l}px; "
            f"border-image: {url(name)} {t} {r} {b} {l}{' fill' if fill else ''} / {t}px {r}px {b}px {l}px stretch;")


