"""
gen_armory_data.py  (Open Vanilla / Duels)

Writes Data/Interface/AddOns/Duels/ArmoryData.lua: what the Armory window's gear picker needs to know about
an item without asking the realm, and every class's vanilla tier sets.

  ArmorySource[item] = "MC" | "ONY" | "BWL" | "ZG" | "AQ20" | "AQ40" | "NAXX" | "PVP<rank>" | "WORLD" | "KIT"
      where the realm's gear picker pool (realm/warfront/warfront_item_pool.sql, made by
      tools/warfront/gen_pool.py from the world database's loot tables) says the item comes from.
      An item with no entry is not in the realm's pool: the Armory shows it but can't put it on.
  ArmoryTierSets[CLASS] = { { tier = "T1", name = "...", source = "MC", items = { ids } }, ... }
      T0 to T3 from the client's own ItemSet.dbc (set name -> item ids). The client files are never
      committed; this file only carries item ids and the sets' names.

  python3 tools/duels/gen_armory_data.py <path to itemset.dbc> realm/warfront/warfront_item_pool.sql \
      Data/Interface/AddOns/Duels/ArmoryData.lua
"""
import re
import struct
import sys

TIERS = ["T0", "T0.5", "T1", "T2", "T2.5", "T3"]
TIER_SOURCE = ["DUNGEON", "DUNGEON", "MC", "BWL", "AQ40", "NAXX"]
SETS = {
    "WARRIOR": ["Battlegear of Valor", "Battlegear of Heroism", "Battlegear of Might", "Battlegear of Wrath",
                "Conqueror's Battlegear", "Dreadnaught's Battlegear"],
    "PALADIN": ["Lightforge Armor", "Soulforge Armor", "Lawbringer Armor", "Judgement Armor",
                "Avenger's Battlegear", "Redemption Armor"],
    "HUNTER": ["Beaststalker Armor", "Beastmaster Armor", "Giantstalker Armor", "Dragonstalker Armor",
               "Striker's Garb", "Cryptstalker Armor"],
    "ROGUE": ["Shadowcraft Armor", "Darkmantle Armor", "Nightslayer Armor", "Bloodfang Armor",
              "Deathdealer's Embrace", "Bonescythe Armor"],
    "PRIEST": ["Vestments of the Devout", "Vestments of the Virtuous", "Vestments of Prophecy",
               "Vestments of Transcendence", "Garments of the Oracle", "Vestments of Faith"],
    "SHAMAN": ["The Elements", "The Five Thunders", "The Earthfury", "The Ten Storms", "Stormcaller's Garb",
               "The Earthshatterer"],
    "MAGE": ["Magister's Regalia", "Sorcerer's Regalia", "Arcanist Regalia", "Netherwind Regalia",
             "Enigma Vestments", "Frostfire Regalia"],
    "WARLOCK": ["Dreadmist Raiment", "Deathmist Raiment", "Felheart Raiment", "Nemesis Raiment",
                "Doomcaller's Attire", "Plagueheart Raiment"],
    "DRUID": ["Wildheart Raiment", "Feralheart Raiment", "Cenarion Raiment", "Stormrage Raiment",
              "Genesis Raiment", "Dreamwalker Raiment"],
}
SOURCE_CODE = {"Molten Core": "MC", "Onyxia's Lair": "ONY", "Blackwing Lair": "BWL", "Zul'Gurub": "ZG",
               "Ruins of Ahn'Qiraj": "AQ20", "Temple of Ahn'Qiraj": "AQ40", "Naxxramas": "NAXX",
               "world drop": "WORLD", "kit": "KIT"}


def item_sets(path):
    b = open(path, "rb").read()
    magic, n, fields, size, _ = struct.unpack("<4s4I", b[:20])
    if magic != b"WDBC" or fields != 45:
        raise SystemExit("not a 1.12 ItemSet.dbc")
    recs, strs = b[20:20 + n * size], b[20 + n * size:]
    out = {}
    for i in range(n):
        r = struct.unpack("<%dI" % fields, recs[i * size:(i + 1) * size])
        end = strs.index(b"\0", r[1])
        out[strs[r[1]:end].decode("utf-8")] = [x for x in r[10:27] if x]
    return out


def pool(path):
    out = {}
    for m in re.finditer(r"\((\d+),(\d+),'((?:[^']|'')*)'\)", open(path, encoding="utf-8").read()):
        src = m.group(3).replace("''", "'")
        code = SOURCE_CODE.get(src)
        if not code:
            pm = re.match(r"PvP rank (\d+)$", src)
            code = "PVP" + pm.group(1) if pm else "WORLD"
        out[int(m.group(1))] = code
    return out


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(dbc, pool_sql, out_path):
    sets, src = item_sets(dbc), pool(pool_sql)
    lines = ["-- Open Vanilla Armory data (generated by tools/duels/gen_armory_data.py; do not edit)",
             "-- ArmorySource: where the realm's gear picker pool says an item comes from (no entry: not in the pool)",
             "ArmorySource = {"]
    for item in sorted(src):
        lines.append("  [%d] = %s," % (item, lua_str(src[item])))
    lines.append("}")
    lines.append("-- ArmoryTierSets: each class's vanilla tier sets, T0 to T3 (item ids from ItemSet.dbc)")
    lines.append("ArmoryTierSets = {")
    for cls in sorted(SETS):
        lines.append("  %s = {" % cls)
        for tier, source, name in zip(TIERS, TIER_SOURCE, SETS[cls]):
            ids = sets.get(name)
            if not ids:
                raise SystemExit("no item set named " + name)
            lines.append("    { tier = %s, name = %s, source = %s, items = { %s } }," % (
                lua_str(tier), lua_str(name), lua_str(source), ", ".join(str(i) for i in ids)))
        lines.append("  },")
    lines.append("}")
    open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("%s: %d pool items, %d classes" % (out_path, len(src), len(SETS)))


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3])
