#!/usr/bin/env python3
"""
gen_sell_prices.py - build Data/Interface/AddOns/Prices/SellData.lua from a ClassicDB dump.

The 1.12 client has no sell-price API, so Prices ships what a merchant pays for every item
(item_template.SellPrice of the CMaNGOS classic world database, the same table our realm's
server reads). Realm-custom items are not in it; for those Prices uses the server's LG packets
and what it learns at merchants (buyback prices).

    python3 tools/gen_sell_prices.py [ClassicDB_1_12_1_zNNNN.sql.gz] [out.lua]

The output is one Lua string "id:price;id:price;..." (ids ascending) that Prices parses once at
load, so the file stays small and loads in one constant.
"""
import gzip
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
DEFAULT_SRC = "/tmp/claude-0/cdb/Full_DB/ClassicDB_1_12_1_z2815.sql.gz"
DEFAULT_OUT = os.path.join(REPO, "Data", "Interface", "AddOns", "Prices", "SellData.lua")


def tuples(values):
    """Yield the field lists of 'VALUES (...),(...);' honouring quoted strings."""
    i, n = 0, len(values)
    while i < n:
        if values[i] != "(":
            i += 1
            continue
        i += 1
        fields, cur, quoted = [], [], False
        while i < n:
            c = values[i]
            if quoted:
                if c == "\\":
                    cur.append(values[i + 1]); i += 2; continue
                if c == "'":
                    if i + 1 < n and values[i + 1] == "'":
                        cur.append("'"); i += 2; continue
                    quoted = False; i += 1; continue
                cur.append(c); i += 1; continue
            if c == "'":
                quoted = True
            elif c == ",":
                fields.append("".join(cur)); cur = []
            elif c == ")":
                fields.append("".join(cur)); i += 1
                break
            else:
                cur.append(c)
            i += 1
        yield fields


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC
    out = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT
    cols = None
    prices = {}
    opener = gzip.open if src.endswith(".gz") else open
    with opener(src, "rt", encoding="utf-8", errors="replace") as f:
        in_create = False
        for line in f:
            if line.startswith("CREATE TABLE `item_template`"):
                in_create, cols = True, []
                continue
            if in_create:
                m = re.match(r"\s+`(\w+)`", line)
                if m:
                    cols.append(m.group(1))
                elif line.startswith(")"):
                    in_create = False
                continue
            if line.startswith("INSERT INTO `item_template` VALUES"):
                e, s = cols.index("entry"), cols.index("SellPrice")
                for t in tuples(line[line.index("VALUES") + 6:]):
                    try:
                        entry, sell = int(t[e]), int(t[s])
                    except (ValueError, IndexError):
                        continue
                    if sell > 0:
                        prices[entry] = sell
    if not prices:
        sys.exit("no item_template SellPrice rows found in " + src)
    body = ";".join("%d:%d" % (k, prices[k]) for k in sorted(prices))
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- SellData.lua: what a merchant pays for one of each item (copper), from the CMaNGOS\n")
        f.write("-- classic world database (item_template.SellPrice, ClassicDB 1.12.1).\n")
        f.write("-- Generated by tools/gen_sell_prices.py; do not edit by hand. %d items.\n" % len(prices))
        f.write("Ledger_SellData = \"%s\"\n" % body)
    print("wrote %s: %d items, %d bytes" % (out, len(prices), os.path.getsize(out)))


if __name__ == "__main__":
    main()
